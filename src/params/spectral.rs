pub const fn amp(h: usize) -> u32 {
    HARMONIC_BASE + h as u32 * 2
}
pub const fn phase(h: usize) -> u32 {
    amp(h) + 1
}
pub fn harmonic(id: u32) -> Option<(usize, bool)> {
    let n = id.checked_sub(HARMONIC_BASE)? as usize;
    (n < HARMONICS * 2).then_some((n / 2, n % 2 == 1))
}
