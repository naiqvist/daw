pub const HARMONICS: usize = 128;
pub const LOG: &[u32] = &[
    ATTACK,
    DECAY,
    RELEASE,
    ORNAMENT_TIME,
    ORNAMENT_SPEED,
    PITCH_TIME,
    PITCH_SPEED,
    VIBRATO_SPEED,
];
pub fn norm(id: u32, value: f32) -> f32 {
    let Some(p) = TABLE.get(id as usize) else {
        return 0.0;
    };
    let value = if value.is_finite() {
        value.clamp(p.min, p.max)
    } else {
        p.default
    };
    if LOG.contains(&id) {
        (value / p.min).ln() / (p.max / p.min).ln()
    } else {
        (value - p.min) / (p.max - p.min)
    }
}
pub fn value(id: u32, norm: f32) -> f32 {
    let Some(p) = TABLE.get(id as usize) else {
        return 0.0;
    };
    let norm = if norm.is_finite() {
        norm.clamp(0.0, 1.0)
    } else {
        return p.default;
    };
    let v = if LOG.contains(&id) {
        p.min * (p.max / p.min).powf(norm)
    } else {
        p.min + norm * (p.max - p.min)
    };
    if discrete(id) { v.round() } else { v }
}
pub fn discrete(id: u32) -> bool {
    matches!(id, ORNAMENT | PITCH_ORNAMENT | MONO)
}
