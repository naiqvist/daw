/// A slider of the kiln's engine: what the lab calls a parameter.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct LabParam {
    pub name: &'static str,
    pub group: &'static str,
    pub min: f32,
    pub max: f32,
    pub default: f32,
    pub unit: &'static str,
}

const fn p(
    name: &'static str,
    group: &'static str,
    min: f32,
    max: f32,
    default: f32,
    unit: &'static str,
) -> LabParam {
    LabParam {
        name,
        group,
        min,
        max,
        default,
        unit,
    }
}

