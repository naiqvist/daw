    /// This is the refusal-channel contract: a bound keystroke cannot be
    /// absorbed between dispatch and state. It must change focus or leave a
    /// reason in the one refusal slot.
    #[test]
    fn every_dispatched_key_changes_state_or_produces_a_refusal() {
        for scope in keymap::ScopeContext::ALL {
            for (modifiers, key) in keymap::bound_chords() {
                let Some(_intent) =
                    keymap::dispatch(scope, keymap::StageInput::Chord(modifiers, key))
                else {
                    continue;
                };
                let mut stage = Stage::new();
                match scope {
                    keymap::ScopeContext::Nested => {
                        assert_eq!(
                            stage.handle_key(Modifiers::NONE, Key::Enter),
                            Some(ApplyOutcome::Changed)
                        );
                    }
                    keymap::ScopeContext::Browser => {
                        assert_eq!(
                            stage.handle_key(Modifiers::COMMAND, Key::F),
                            Some(ApplyOutcome::Changed)
                        );
                    }
                    keymap::ScopeContext::Mixer => {
                        assert_eq!(command(&mut stage, Key::M), ApplyOutcome::Changed);
                    }
                    keymap::ScopeContext::Rename => {
                        assert_eq!(
                            stage.handle_key(Modifiers::NONE, Key::F2),
                            Some(ApplyOutcome::Changed)
                        );
                    }
                    keymap::ScopeContext::Chain => {
                        into_chain(&mut stage);
                    }
                    keymap::ScopeContext::Clip => {
                        into_clip(&mut stage);
                    }
                    keymap::ScopeContext::Root => {}
                }
                // Everything a key is allowed to change. A new piece of
                // state belongs in this tuple the day it is added: what
                // is absent here is state a key could change while this
                // test still called the key a liar.
                let before = (
                    stage.focus.clone(),
                    stage.transport,
                    stage.help,
                    stage.browser.clone(),
                    stage.mixing,
                    stage.playing.clone(),
                    stage.song.clone(),
                    stage.polarity,
                    stage.chain.clone(),
                    // Tuples stop at twelve; the document's own state
                    // rides as one.
                    (
                        stage.renaming.clone(),
                        stage.nudging,
                        stage.clipboard.clone(),
                        stage.path.clone(),
                    ),
                );

                match stage.handle_key(modifiers, key) {
                    Some(ApplyOutcome::Changed) => {
                        assert_ne!(
                            (
                                stage.focus.clone(),
                                stage.transport,
                                stage.help,
                                stage.browser.clone(),
                                stage.mixing,
                                stage.playing.clone(),
                                stage.song.clone(),
                                stage.polarity,
                                stage.chain.clone(),
                                (
                                    stage.renaming.clone(),
                                    stage.nudging,
                                    stage.clipboard.clone(),
                                    stage.path.clone(),
                                ),
                            ),
                            before,
                            "{scope:?} + {key:?} lied about changing"
                        );
                        assert_eq!(stage.refusal, None);
                    }
                    Some(ApplyOutcome::Refused(refusal)) => {
                        assert_eq!(
                            (
                                stage.focus.clone(),
                                stage.transport,
                                stage.help,
                                stage.browser.clone(),
                                stage.mixing,
                                stage.playing.clone(),
                                stage.song.clone(),
                                stage.polarity,
                                stage.chain.clone(),
                                (
                                    stage.renaming.clone(),
                                    stage.nudging,
                                    stage.clipboard.clone(),
                                    stage.path.clone(),
                                ),
                            ),
                            before,
                            "{scope:?} + {key:?} changed and refused"
                        );
                        assert_eq!(stage.refusal, Some(refusal));
                    }
                    None => panic!("{scope:?} + {key:?} disappeared after dispatch"),
                }
            }
        }

        let mut stage = Stage::new();
        let _ = command(&mut stage, Key::F);
        let before = stage.browser.clone();
        assert_eq!(type_text(&mut stage, "k"), vec![ApplyOutcome::Changed]);
        assert_ne!(stage.browser, before, "browser text was swallowed");
    }

