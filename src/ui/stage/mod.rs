/// The periphery: two fixed strips framing one sovereign field. Zones are
/// keyed by FUNCTION (ancestry, vitals, messages), never by content, and
/// they never take focus — the cursor lives only in the field.
///
/// The height is a LAYOUT dimension rather than a spacing rung: it was
/// settled by eye on the display this is read on, and the spacing ladder
/// is for the distances between things, not for how big a zone is.
const PERIPHERY_H: f32 = 64.0;

/// A track column. A layout dimension like [`BROWSER_W`], and fixed for
/// the same reason: geometry that resized itself with the track count
/// would move the ground under a cursor that had already learned where
/// each track lives.
const TRACK_W: f32 = 132.0;
const TRACK_H: f32 = 64.0;

/// The gutter left of the session where each scene's address is written.
/// A layout dimension: two digits of the smallest type and a breath, and
/// it is reserved whether or not there are scenes to number, so the
/// columns never shift when the first scene arrives.
const ADDRESS_W: f32 = 28.0;

/// Between one track column and the next.
///
/// WIDER than the gap between the slots stacked inside a column, and that
/// difference is the whole point: proximity is what groups marks, so the
/// eye reads a column as one thing before it reads a row. With both gaps
/// equal the lattice reads as an even mesh and neither axis wins, which
/// is what made a session of scattered clips hard to scan.
fn column_gap() -> f32 {
    design::px(design::space::STEP)
}

/// Between the slots stacked inside one column.
fn row_gap() -> f32 {
    design::px(design::space::HAIR)
}

/// Between the head and the first cell under it: NOTHING.
///
/// They touch, because they are one thing. A head and the cells beneath
/// it are a column — the head names it and the cells are what is in it —
/// and a break between them made the strip read as two stacked bands
/// that happened to line up rather than as a row of columns.
///
/// So the surface has two distances, not three: none inside a column,
/// and a gap between columns. The only boundary left is the one that
/// separates things which really are separate.
///
/// A rule was tried here first and taken out again — it drew a boundary
/// the space already drew — and then the space itself turned out to be
/// drawing a boundary that was not there.
fn section_gap() -> f32 {
    0.0
}

/// The sign for a place with nothing in it: a point, the smallest mark
/// the surface can make. An empty slot is drawn as one point rather than
/// as a plane, so the session reads as clips on a ground instead of a
/// grid of squares — the lattice is still there, in the points' rank
/// and file, but it is the ground and the clips are the figure.
const POINT: f32 = 3.0;

/// The sequencer's band: a fixed tray along the foot of the field, where
/// the clip under the cursor is shown and, once entered, edited. A layout
/// dimension like [`PERIPHERY_H`]: tall enough for the grid at its
/// largest cell with the trig inspector beside it, and it does not move
/// or vanish — a band with no clip to show simply goes quiet, so the
/// session above it never changes shape when a clip opens or closes.
const CLIP_H: f32 = 272.0;

/// The widest the sequencer is drawn: the inspector, the grid at its
/// largest cell, and their gaps. Past this the band is left empty rather
/// than stretched, so the grid keeps a size the eye has learned.
const CLIP_W_MAX: f32 = 1080.0;

/// The browser's column. A layout dimension like [`PERIPHERY_H`]: wide
/// enough that a file name is a name rather than an ellipsis, and it does
/// not move, because a zone the eye has learned is only free to read while
/// it stays where it was learned.
const BROWSER_W: f32 = 320.0;

/// How long the browser takes to arrive, and to leave.
///
/// Short enough that it never stands between a keystroke and the thing it
/// asked for — a panel you wait for is a panel you stop summoning.
const BROWSER_SLIDE_S: f32 = 0.12;

/// Where every zone sits, as a pure function of the window.
///
/// It takes NO state — not focus, not whether the browser is summoned,
/// not what is being shown. That is the whole point: every zone is a
/// fixed place the eye can learn once and read for free forever, and a
/// place that moves has to be found again every time. Zones go quiet, and
/// they go empty, but they never move and they never resize.
///
/// The browser OVERLAYS the field rather than dividing it. Both own the
/// same corner of the screen and neither yields any of it: the field is
/// laid out as though the browser did not exist, and the browser is drawn
/// over the top of it when summoned. Content beneath is hidden for a
/// moment, and hidden is not the same as moved — nothing has to be found
/// again when the browser goes away.
#[derive(Clone, Copy, Debug, PartialEq)]
struct Layout {
    vitals: egui::Rect,
    breadcrumb: egui::Rect,
    transport: egui::Rect,
    message: egui::Rect,
    browser: egui::Rect,
    /// The whole middle band: session and clip tray together. The
    /// codebook takes all of it.
    field: egui::Rect,
    /// The session: heads and the scene lattice.
    session: egui::Rect,
    /// The clip tray: the sequencer, or quiet.
    clip: egui::Rect,
}

impl Layout {
    fn of(whole: egui::Rect) -> Self {
        let vitals = egui::Rect::from_min_max(
            whole.min,
            egui::pos2(whole.max.x, whole.min.y + PERIPHERY_H),
        );
        // The time end is a fixed number of the design alphabet's largest
        // spacing cells. It never grows with the readout or meter, so a
        // changing song fact cannot move either half of the strip.
        let transport_w = design::px(design::space::VAST) * 8.0;
        let transport_x = (vitals.max.x - transport_w).max(vitals.min.x);
        let breadcrumb =
            egui::Rect::from_min_max(vitals.min, egui::pos2(transport_x, vitals.max.y));
        let transport = egui::Rect::from_min_max(egui::pos2(transport_x, vitals.min.y), vitals.max);
        let message = egui::Rect::from_min_max(
            egui::pos2(whole.min.x, whole.max.y - PERIPHERY_H),
            whole.max,
        );
        // The browser holds the left of the middle band, INSIDE the strips
        // rather than beside them: vitals and messages speak for the whole
        // app, while the browser is content and sits with the content.
        let band = egui::Rect::from_min_max(
            egui::pos2(whole.min.x, vitals.max.y),
            egui::pos2(whole.max.x, message.min.y),
        );
        let browser =
            egui::Rect::from_min_max(band.min, egui::pos2(band.min.x + BROWSER_W, band.max.y));
        // The clip tray is cut off the FOOT of the field, fixed: the
        // session above keeps the same shape whether or not the tray has
        // anything to show.
        let clip_top = (band.max.y - CLIP_H).max(band.min.y);
        let session = egui::Rect::from_min_max(band.min, egui::pos2(band.max.x, clip_top));
        let clip = egui::Rect::from_min_max(egui::pos2(band.min.x, clip_top), band.max);
        Self {
            vitals,
            breadcrumb,
            transport,
            message,
            browser,
            field: band,
            session,
            clip,
        }
    }
}

/// The clip the cursor went into: which pattern, and from which track's
/// column — the track decides the pitch language the sequencer speaks.
/// Track is an index because tracks only ever append while a clip is
/// open; the pattern is an id because a clip cannot be cleared from
/// inside it, so the id stays valid for as long as the cursor is in there.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct Opened {
    pub pattern: PatternId,
    pub track: usize,
}

/// Why an intent could not change the stage state.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum RefusalReason {
    /// A step with no neighbour in that direction in the active scope.
    Edge(Step),
    /// Enter at the depth cap: the focused square would not open.
    Deeper,
    /// Escape at the root: there is no further out.
    Shallower,
    /// Asked of a place that holds nothing yet.
    Empty,
    /// The song clock is already at its first tick.
    AtTop,
    /// The addressed leaf is real, but this scaffolding has no verb for it.
    Unavailable,
}

/// A rejected application. The intent remains attached to its reason so
/// future callers can report precisely what the stage declined.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct Refusal {
    pub intent: StageIntent,
    pub reason: RefusalReason,
}

/// The exhaustive result of applying an intent: it changed the state or it
/// produced a drawable reason. There is no silent third outcome.
#[must_use]
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum ApplyOutcome {
    Changed,
    Refused(Refusal),
}

/// Everything the stage knows. Every field added here should have to
/// justify itself — this is the mutable core that the rest of the surface
/// will be a pure function of.
pub struct Stage {
    focus: FocusStack,
    /// Canonical musical facts. Tempo and meter are read from here on every
    /// frame; the transport never keeps a second copy of either.
    song: Song,
    /// The green-zone clock mirror. A frame delta drives it until an engine
    /// can replace that source without changing anything downstream.
    transport: Transport,
    /// The browser as it was last drawn, kept for exactly as long as it
    /// takes to slide away.
    ///
    /// A panel that animates open and then vanishes on close is worse
    /// than one that never animates: the motion teaches the eye to
    /// expect a return trip that never comes. Holding the last state
    /// while it leaves is what buys the second half of the gesture.
    browser_leaving: Option<Browser>,
    /// The browser, when it has been summoned. `Some` means focus is IN
    /// it: the browser is a place rather than a panel, so it either holds
    /// the cursor or it is not on screen at all.
    ///
    /// Not a level of [`Self::focus`], because it is not inside anything —
    /// descending into a track and going off to the library are different
    /// motions, and a stack that conflated them would draw a false
    /// ancestry.
    browser: Option<Browser>,
    /// Whether the codebook is showing. A summoned surface rather than
    /// standing chrome: a permanent key list is ambient information, and
    /// ambient information is what this stage spends its budget avoiding.
    help: bool,
    /// Latest refusal in this frame. Cleared at the next `show`, and drawn
    /// from one site after every key has been applied.
    refusal: Option<Refusal>,
    /// The first track the strip draws. Retained rather than derived
    /// because MINIMAL scrolling is a memory: where the view already sits
    /// decides whether it needs to move at all, and a view recomputed from
    /// the cursor alone could only recentre.
    strip_offset: usize,
    /// The first scene the lattice draws. The same minimal-scroll memory
    /// as [`Self::strip_offset`], on the other axis.
    scene_offset: usize,
    /// The clip the cursor is inside, while the nested level is the
    /// sequencer. `None` while the nested level is the calibration field
    /// or there is no nested level.
    inside: Option<Opened>,
    /// The sequencer — the same one the second frame draws, lifted to a
    /// neutral home. It owns its own step cursor, resolution and editor
    /// choice; the stage owns WHERE it is drawn and WHEN it has the keys.
    sequencer: sequence::SequencePanel,
    /// The grammar's sentence-in-progress and its registers: the frame's
    /// keyboard layer, above the panel, so a count started before a focus
    /// change does not vanish.
    sentence: grammar::Sentence,
    registers: registers::Registers,
    /// Letters as pitches, while `I` says so. Announced on the message
    /// strip, because a mode that does not announce itself is a trap.
    midi_typing: midi_typing::MidiTyping,
    /// A pitch typed this frame, waiting for the sequencer to enter it.
    entered_pitch: Option<Pitch>,
    /// The last notice — a refused edit in the sequencer's own words, or
    /// the value a mixer verb just set — held on the message strip until
    /// the next one replaces it.
    ///
    /// Owned text rather than a static word, because a fader's notice is
    /// a NUMBER: a control the hand moves and the eye cannot read exactly
    /// has to say what it landed on, or setting a level becomes guessing
    /// at one.
    notice: Option<String>,
    /// Green-zone scanner ownership and the last immutable answer it gave.
    /// The browser never walks the filesystem from a frame.
    library_service: LibraryService,
    library_snapshot: LibrarySnapshot,
    library_scanning: bool,
    /// The scene that is playing, if one has been fired.
    ///
    /// NOT document data, and the model says why: a scene is "a place to
    /// keep clips before it is a thing to fire". What a scene HOLDS
    /// belongs to the song; which one is playing belongs to the
    /// performance — so a project reopened tomorrow does not start making
    /// noise because it was making noise when it was put away.
    /// Which scene's clip each track is playing, indexed by track.
    ///
    /// PER TRACK, because that is what a session is: a row is a set of
    /// clips fired together, not a thing that plays as a unit. Launching
    /// a row sets every entry; launching one clip sets one.
    ///
    /// Frame state, not the document's — a project reopened tomorrow
    /// should not start making noise because it was making noise when it
    /// was put away.
    playing: Vec<Option<usize>>,
    /// What hangs beneath the heads: the scenes, or the mixer. One
    /// lattice, two contents. The columns never move across the change,
    /// which is what lets the eye keep its place.
    mixing: bool,
    /// The meters: what the engine last reported, through the ballistics
    /// that make a per-block peak readable. Empty while nothing is
    /// behind the stage — a meter with no engine draws NOTHING rather
    /// than a guess.
    meters: vitals::Meters,
    /// Bumped by every edit that changes WHAT SOUNDS.
    ///
    /// The host watches this to know when the graph it handed the engine
    /// has gone stale. A cursor move must never bump it: recompiling the
    /// graph under a moving cursor would break the sound for nothing.
    revision: u64,
    /// What the host says about the engine behind this frame: whether
    /// there is one, whether it is alive, and what it has dropped.
    ///
    /// The stage cannot ask — it holds no engine and never will — so this
    /// is pushed in beside the levels. Worth ink on the periphery:
    /// silence with a running engine is a musical problem, silence with
    /// no engine at all is a different one, and a glitch that went by
    /// unannounced is a third — and a surface that draws them the same
    /// way makes the reader guess which they have.
    vitals: vitals::Vitals,
    /// The engine's own position, in beats, as the host last read it
    /// back — taken once per frame by `show` and then gone. While it
    /// arrives, the playhead is what SOUNDED; while it does not, the
    /// frame clock stands in, exactly as it did before there was an
    /// engine to read.
    engine_beat: Option<f64>,
    /// Bumped whenever the stage moves its own clock somewhere the engine
    /// did not: a return to the top. The host watches it, as it watches
    /// the revision, and tells the engine to agree.
    seeks: u64,
    /// The last frame's length, for the things that move on their own
    /// between one `show` and the next: meters falling, a flash burning
    /// down.
    frame_dt: f32,
    /// Every settled state of the song, for stepping back through.
    ///
    /// Observed after every intent rather than at the end of the frame:
    /// an intent is the unit a performer thinks in, and the unit they
    /// expect to take back.
    history: History<Song>,
    /// The file the song came from, or was last saved to. `None` is a
    /// song that has never touched disk, and the first save says where
    /// it went.
    path: Option<PathBuf>,
    /// Where a song with no file of its own is saved, if the host gave
    /// the stage a folder for songs. Without one a first save is
    /// refused rather than landing somewhere nobody chose — and a
    /// headless stage never writes to disk by accident.
    home: Option<PathBuf>,
    /// Whether the song differs from what is on disk.
    dirty: bool,
    /// A rename in flight. `Some` means the letters are the keyboard's
    /// meaning — see `keymap::ScopeContext::Rename`.
    renaming: Option<Rename>,
    /// A nudge has been spoken and is waiting for its direction. The
    /// grammar's own shape — verb, then motion — and it lasts exactly
    /// one intent: anything but a Left or a Right lets it go.
    nudging: bool,
    /// The device most recently yanked, with its settings, waiting to be
    /// put down. Kept rather than consumed by a put, so one device can
    /// be put on several tracks.
    clipboard: Option<Device>,
    /// Bumped by every edit a running graph can absorb as a letter — a
    /// fader, a pan. See [`Self::mix_revision`].
    mix_revision: u64,
    /// The command palette: everything the stage can do from here, by
    /// name, for the times the codebook is not already in the fingers.
    ///
    /// It opens WITH the app. An empty stage is a surface with no
    /// affordances on it at all, and the palette is the one place that
    /// says what exists — so the way in is the same door a performer
    /// uses later, rather than a splash screen that has to be dismissed
    /// before the app begins.
    palette: crate::ui::palette::Palette,
    /// The chain band, when it is showing. `Some` means focus is IN it:
    /// a lattice whose columns are the addressed track's devices and
    /// whose rows are that device's parameters.
    ///
    /// A place beside the session rather than a level inside it, for the
    /// same reason the browser is one — going to look at a track's
    /// devices is not descending into the slot the cursor is on, and a
    /// stack that conflated them would draw a false ancestry.
    chain: Option<FocusLattice>,
    /// The first parameter row the band draws, shared by every column so
    /// the rows line up across devices.
    chain_offset: usize,
    /// Which side of the luminance field the ground is on.
    ///
    /// One code, two projections — never two palettes. Every role keeps
    /// its tier and its channels across the change; only the direction of
    /// contrast turns over. Dark is the house default and light is the
    /// daylight answer, so this is a viewing condition rather than a
    /// preference about how the app should look.
    polarity: design::Polarity,
}

/// A track's name being typed.
///
/// It opens holding the name the track already has, so Enter straight
/// away keeps it — and `fresh` says nothing has been typed yet, so the
/// first letter REPLACES that name rather than appending to it. That is
/// the shape a selected field has in every editor: the old name is
/// there to read and to keep, and gone the moment a new one starts.
#[derive(Clone, Debug, Eq, PartialEq)]
struct Rename {
    track: usize,
    text: String,
    fresh: bool,
}

/// One meter reading: the two sides, as linear amplitude where 1.0 is
/// full scale.
///
/// A PAIR rather than a number because the engine reports the sides
/// separately and the strip draws them separately. A mono source arrives
/// with both sides equal, which is the truth about a mono source rather
/// than a second meter invented to fill a space.
#[derive(Clone, Copy, Debug, Default, PartialEq)]
pub struct Level {
    pub left: f32,
    pub right: f32,
}

impl Level {
    /// The louder side. What a single mark stands for when there is only
    /// room for one.
    pub fn peak(self) -> f32 {
        self.left.max(self.right)
    }
}

impl Default for Stage {
    fn default() -> Self {
        Self::with_library(LibraryConfig::default(), LibrarySnapshot::default())
    }
}

impl Stage {
    pub fn new() -> Self {
        Self::default()
    }

    /// Start the neutral scanner while retaining a cached catalog to show
    /// until its newer answer arrives.
    pub fn with_library(config: LibraryConfig, cached: LibrarySnapshot) -> Self {
        let song = Song::default();
        Self {
            // The root is the session: the song's tracks across, the
            // scenes down, with the heads as the first row. The calibration
            // field remains what a head OPENS INTO: a track's content is
            // not designed yet, and an honest placeholder is better than a
            // surface that pretends to hold clips it cannot.
            focus: FocusStack::new(
                // One column per track, and one more for the master.
                FocusScope::lattice(song.tracks.len() + 1, scenes::lattice_rows(&song)),
                MAX_DEPTH,
            ),
            song,
            transport: Transport::new(),
            browser: None,
            browser_leaving: None,
            help: false,
            refusal: None,
            strip_offset: 0,
            scene_offset: 0,
            inside: None,
            sequencer: sequence::SequencePanel::default(),
            sentence: grammar::Sentence::default(),
            registers: registers::Registers::default(),
            midi_typing: midi_typing::MidiTyping::default(),
            entered_pitch: None,
            notice: None,
            library_service: LibraryService::start(config),
            library_snapshot: cached,
            library_scanning: true,
            playing: Vec::new(),
            vitals: vitals::Vitals::default(),
            engine_beat: None,
            seeks: 0,
            frame_dt: 0.0,
            history: History::new(Song::default()),
            path: None,
            home: None,
            dirty: false,
            renaming: None,
            nudging: false,
            clipboard: None,
            mixing: false,
            meters: vitals::Meters::default(),
            revision: 0,
            mix_revision: 0,
            chain: None,
            chain_offset: 0,
            // Light, for now. The ALPHABET's default is dark and stays
            // dark — this is the frame choosing which of the two grounds
            // it opens on while the light one is being lived with, not a
            // change to which one the code considers its house default.
            polarity: design::Polarity::Light,
            palette: {
                let mut palette = crate::ui::palette::Palette::default();
                palette.open();
                palette
            },
        }
    }

    pub fn library_snapshot(&self) -> &LibrarySnapshot {
        &self.library_snapshot
    }

    /// The alphabet this frame is drawing in.
    ///
    /// EVERY mark on this surface reads its value from here rather than
    /// from a constant, which is what makes the ground switchable at all:
    /// a colour named at compile time is a colour that cannot turn over.
    fn alphabet(&self) -> &'static design::Alphabet {
        design::Alphabet::for_polarity(self.polarity)
    }

    /// Open or dismiss the command palette without a keystroke.
    ///
    /// For a host that would rather the app did not start on it, and for
    /// the shot harness, which has no keyboard to press Escape with.
    pub fn set_palette_open(&mut self, open: bool) {
        if open {
            self.palette.open();
        } else {
            self.palette.close();
        }
    }

    /// Which ground the stage is on, for a host that has to make the
    /// window and the stock widgets agree with it.
    pub fn polarity(&self) -> design::Polarity {
        self.polarity
    }

    /// A resting plane: where a thing is, carrying structure and not news.
    fn square(&self) -> egui::Color32 {
        self.alphabet().surface.color
    }

    /// The marked one. Exactly one thing on the screen is ever this.
    fn focused(&self) -> egui::Color32 {
        self.alphabet().focus.color
    }

    /// What a refusal is drawn in.
    fn refusal_ink(&self) -> egui::Color32 {
        self.alphabet().ink.color
    }

    /// Where focus WILL be when it comes back, drawn while it is
    /// somewhere else — a whole rung below focus, so the rule holds that
    /// only one thing is focus-bright.
    fn resting(&self) -> egui::Color32 {
        self.alphabet().ink.color
    }

    /// What the clip tray is drawn through while the cursor is not in it.
    ///
    /// The veil takes the surface TOWARD THE GROUND, so which way it
    /// pulls turns over with the polarity: pulling a light page toward
    /// black would make the resting tray louder than the live one, which
    /// is the opposite of what a veil is for.
    fn veil(&self) -> egui::Color32 {
        match self.polarity {
            design::Polarity::Dark => egui::Color32::from_black_alpha(150),
            design::Polarity::Light => egui::Color32::from_white_alpha(150),
        }
    }

    /// The document, for a host that has to turn it into sound.
    ///
    /// Read-only on purpose: the stage owns every edit to the song, so a
    /// host holding this cannot change what it is looking at. The whole
    /// audio path is a pure function of what these four report.
    pub fn song(&self) -> &Song {
        &self.song
    }

    /// The document, for a harness that needs to arrange a state the
    /// keyboard cannot reach yet. Not for a host: every edit a performer
    /// can make goes through an intent.
    pub fn song_mut(&mut self) -> &mut Song {
        &mut self.song
    }

    /// What each track is playing, for a host that has to turn it into
    /// sound. Index-aligned to the song's tracks.
    pub fn playing(&self) -> &[Option<usize>] {
        &self.playing
    }

    /// The scene a track is playing, if it is playing one.
    fn playing_on(&self, track: usize) -> Option<usize> {
        self.playing.get(track).copied().flatten()
    }

    /// Keep the playing table the same length as the song's tracks. A
    /// track that has just been made is playing nothing, which is what an
    /// absent entry already means — this only stops the table falling
    /// behind the song it is indexed against.
    fn fit_playing(&mut self) {
        self.playing.resize(self.song.tracks.len(), None);
    }

    /// Bumped whenever what should be sounding has changed. A host that
    /// remembers the last value it saw knows exactly when to recompile,
    /// and never recompiles for a cursor.
    pub fn revision(&self) -> u64 {
        self.revision
    }

    /// The tempo where the playhead stands, for a host that has to tell
    /// an engine how fast the song goes. Read from the song's own map, so
    /// there is no second tempo anywhere.
    pub fn bpm(&self) -> f64 {
        self.song
            .bpm_at(self.transport.tick(), transport::DEFAULT_BPM)
    }

    /// Whether the transport is asking to roll. The stage's clock is the
    /// green-zone mirror; the host makes the engine agree with it.
    pub fn rolling(&self) -> bool {
        self.transport.motion().is_rolling()
    }

    /// Hand the stage what the engine measured. Index-aligned to the
    /// song's tracks; a track past the end of `tracks` reads as silence,
    /// which is also what a track with no voice reads as.
    ///
    /// The stage never asks the engine for anything — telemetry is
    /// pushed in, exactly as edits are pushed out. That is what keeps
    /// this frame free of the audio layer entirely.
    /// Tell the stage how the engine behind it is doing.
    pub fn set_health(&mut self, health: Health) {
        self.vitals.report(health);
    }

    /// Hand the stage what the engine measured this frame. The meters
    /// move toward it at the rate the last frame took, which is what
    /// keeps a per-block peak from flickering.
    pub fn set_levels(&mut self, tracks: &[Level], master: Level) {
        self.meters.follow(tracks, master, self.frame_dt);
    }

    /// Tell the stage where the engine's transport is, in beats. Read
    /// once by the next `show` and then forgotten: a position is a fact
    /// about NOW, and one kept past its frame would be a clock running
    /// backwards.
    pub fn set_position(&mut self, beat: f64) {
        self.engine_beat = Some(beat);
    }

    /// How many times the stage has moved its own clock somewhere the
    /// engine did not. A host that remembers the last value it saw knows
    /// exactly when to seek the engine.
    pub fn seeks(&self) -> u64 {
        self.seeks
    }

    /// The song's own tick, for a host that has to turn a seek into a
    /// sample position.
    pub fn tick(&self) -> usize {
        self.transport.tick()
    }

    /// The file the song lives in, if it has one yet.
    pub fn path(&self) -> Option<&Path> {
        self.path.as_deref()
    }

    /// Whether the song differs from what is on disk.
    pub fn is_dirty(&self) -> bool {
        self.dirty
    }

    /// Give the stage a folder for songs: where a song that has never
    /// been saved goes on its first save.
    pub fn set_home(&mut self, home: impl Into<PathBuf>) {
        self.home = Some(home.into());
    }

    /// Replace the song with the one in `path`. The performance stops —
    /// nothing plays, focus returns to the top — and history restarts:
    /// undo does not cross a load. A file that will not open changes
    /// nothing and says why.
    pub fn open(&mut self, path: impl Into<PathBuf>) -> Result<(), String> {
        let path = path.into();
        let song = document::load(&path)?;
        self.notice = Some(format!("opened {}", document::title(&path)));
        self.path = Some(path);
        self.replace_song(song);
        self.history = History::new(self.song.clone());
        self.dirty = false;
        Ok(())
    }

    /// Write the song to its file, or into the songs folder if it has no
    /// file yet. Either way the strip says where it went.
    pub fn save(&mut self) -> Result<(), String> {
        let path = match (&self.path, &self.home) {
            (Some(path), _) => path.clone(),
            (None, Some(home)) => document::untitled_in(home),
            (None, None) => return Err("nowhere to save: no songs folder".to_owned()),
        };
        document::save(&path, &self.song)?;
        self.notice = Some(format!("saved {}", path.display()));
        self.path = Some(path);
        self.dirty = false;
        Ok(())
    }

    /// Put a whole new song under the stage — a load, an undo — and
    /// bring every piece of frame state that stands for the song back
    /// into agreement with it.
    ///
    /// Focus comes back to the top and the performance stops. Both are
    /// deliberate: the cursor may have been inside a clip the new song
    /// does not have, and a scene that was playing may not exist. A frame
    /// that guessed at either would be pointing at something the
    /// performer cannot see.
    fn replace_song(&mut self, song: Song) {
        while self.focus.depth() > 1 {
            self.focus.escape();
        }
        self.inside = None;
        self.chain = None;
        self.playing.clear();
        // A song opens parked at its top, and the engine is told so.
        self.transport.stop();
        if self.transport.tick() != 0 {
            self.transport.rewind();
            self.seeks = self.seeks.wrapping_add(1);
        }
        self.adopt_song(song);
    }

    /// Take a song that differs from the one under the stage — an undo,
    /// a redo — keeping focus and the performance wherever the new song
    /// can still honour them. A clip the cursor is inside that the new
    /// song does not have sends focus back to the session; everything
    /// else is clamped rather than reset.
    fn adopt_song(&mut self, song: Song) {
        self.song = song;
        self.renaming = None;
        self.nudging = false;
        if let Some(opened) = self.inside
            && (self.song.pattern(opened.pattern).is_none()
                || opened.track >= self.song.tracks.len())
        {
            while self.focus.depth() > 1 {
                self.focus.escape();
            }
            self.inside = None;
        }
        self.fit_playing();
        self.fit_session();
        self.touched();
    }

    /// Bring the frame's scopes back to the song's shape after an edit
    /// that changed how many tracks or scenes there are, or which devices
    /// are on the addressed chain. The cursor stays where it can, and
    /// comes inside the edge where it cannot.
    fn fit_session(&mut self) {
        let cols = self.song.tracks.len();
        let rows = if self.mixing {
            1
        } else {
            scenes::lattice_rows(&self.song)
        };
        if let FocusScope::Lattice(lattice) = self.focus.root_mut() {
            lattice.resize_cols(cols);
            lattice.resize_rows(rows);
        }
        let scenes = self.song.session.scenes.len();
        for slot in &mut self.playing {
            if slot.is_some_and(|scene| scene >= scenes) {
                *slot = None;
            }
        }
        // The band is one device narrower or wider; the cursor comes
        // back inside it rather than pointing past the end, and a band
        // with nothing left in it closes.
        let (cols, rows) = self.chain_shape();
        match (cols, self.chain.as_mut()) {
            (0, Some(_)) => self.chain = None,
            (_, Some(lattice)) => {
                lattice.resize_cols(cols);
                lattice.resize_rows(rows);
            }
            _ => {}
        }
    }

    /// Note the song as it stands, for undo. Every intent ends here
    /// except the two that walk history themselves.
    fn settle(&mut self) {
        if self.song != *self.history.present() {
            self.history.observe(&self.song);
            self.dirty = true;
        }
    }

    /// How many parameter rows the band shows at once, and only whole
    /// ones. A pure function of the tray, like every other capacity here.
    fn chain_capacity(tray: egui::Rect) -> usize {
        let margin = design::px(design::space::ROOM);
        let head_h = design::px(design::space::OPEN);
        let pitch = design::px(design::space::ROOM);
        chain::rows_that_fit(tray.height() - margin - head_h, pitch)
    }

    /// Where the transport is inside the OPEN clip, in ticks — but only
    /// when that clip is the one its track is actually sounding.
    ///
    /// Three conditions, and each of them is a way for the answer to be
    /// "there is no present moment here": the transport is parked, the
    /// track is playing nothing, or it is playing a different clip from
    /// the one on screen. A playhead drawn in any of those would be the
    /// surface asserting something that is not happening.
    fn playhead(&self, opened: Opened) -> Option<usize> {
        if !self.transport.motion().is_rolling() {
            return None;
        }
        let scene = self.playing_on(opened.track)?;
        let track = self.song.tracks.get(opened.track)?;
        let Clip::Pattern(sounding) = self.song.session.scenes.get(scene)?.clip(track.id)?;
        if sounding != opened.pattern {
            return None;
        }
        // The clip loops, so the moment is the transport folded into the
        // pattern's own length rather than a position that runs off it.
        let length = sequencer::pattern_length(&self.song, opened.pattern).max(1);
        Some(self.transport.tick() % length)
    }

    /// The device the chain band's cursor is on, as an index into the
    /// addressed track's chain.
    fn chained_device(&self) -> Option<(usize, usize)> {
        let track = self.addressed_track()?;
        let (device, _) = self.chain.as_ref()?.cursor()?;
        (device < self.song.tracks[track].chain.len()).then_some((track, device))
    }

    /// The parameter the band's cursor is on: its device, and its id.
    fn chained_param(&self) -> Option<(usize, usize, u32)> {
        let (track, device) = self.chained_device()?;
        let (_, row) = self.chain.as_ref()?.cursor()?;
        let def = self.song.tracks[track].chain[device]
            .kind
            .spec()
            .params
            .get(row)?;
        Some((track, device, def.id))
    }

    /// The lattice the band needs for the chain it is showing: one column
    /// per device, and as many rows as the widest device has parameters.
    ///
    /// Rows are the WIDEST rather than each column's own, so one cursor
    /// addresses the whole band. A column with fewer parameters simply
    /// has nothing on those rows, which the drawing shows by drawing
    /// nothing there.
    fn chain_shape(&self) -> (usize, usize) {
        let Some(track) = self.addressed_track() else {
            return (0, 0);
        };
        let chain = &self.song.tracks[track].chain;
        let rows = chain
            .iter()
            .map(|device| device.kind.spec().params.len())
            .max()
            .unwrap_or(0);
        (chain.len(), rows)
    }

    /// The track the session's cursor ADDRESSES, whether or not focus is
    /// standing there.
    ///
    /// Different from [`Self::focused_track`] on purpose. A mixer verb
    /// may only act where the cursor IS. But the browser is a place
    /// beside the session rather than a level inside it — going off to
    /// the library never moved the session's cursor — so a device picked
    /// there still has a track to land on, and it is the one the strip is
    /// pointing at.
    fn addressed_track(&self) -> Option<usize> {
        let track = self.session_address().and_then(Address::track)?;
        (track < self.song.tracks.len()).then_some(track)
    }

    /// The track the cursor stands in, if it stands in one that exists.
    /// Every mixer verb addresses this and nothing else — there is one
    /// cursor, and a verb that acted on anything but where it stands
    /// would be acting somewhere the performer is not looking.
    fn focused_track(&self) -> Option<usize> {
        let track = self.standing_on().and_then(Address::track)?;
        (track < self.song.tracks.len()).then_some(track)
    }

    /// Bumped when a fader or a pan moved: values the engine takes as a
    /// LETTER to a node that is already running.
    ///
    /// Deliberately not [`Self::revision`]. Rebuilding the graph for a
    /// fader would swap the schedule under a sounding note on every
    /// press — the whole reason the output stage is addressable is so
    /// that a level can change without the sound stopping.
    pub fn mix_revision(&self) -> u64 {
        self.mix_revision
    }

    fn remixed(&mut self) {
        self.mix_revision = self.mix_revision.wrapping_add(1);
    }

    /// Note that what sounds has changed. Called by the edits that change
    /// it and by nothing else — see [`Self::revision`].
    fn touched(&mut self) {
        self.revision = self.revision.wrapping_add(1);
    }

    /// Draw one frame: read the keyboard, advance time, paint the stage.
    pub fn show(&mut self, ui: &mut egui::Ui) {
        self.refusal = None;
        self.poll_library(ui.ctx());

        // `:` summons the palette, the same key it answers to in the frame
        // before this one. Checked before anything else reads the
        // keyboard, and not while it is already open, so a held key
        // cannot reset what has been typed into it.
        if !self.palette.is_open()
            && ui.input_mut(|input| input.consume_key(egui::Modifiers::NONE, egui::Key::Colon))
        {
            self.palette.open();
        }
        if let Some(intent) = self.pump_palette(ui.ctx()) {
            let _ = self.apply(intent);
        }
        // While the palette is open it owns the keyboard OUTRIGHT. It
        // consumes the keys it uses itself; this is about the rest —
        // typing "mute" to find a verb must not also play the transport
        // on its way past.
        let palette_open = self.palette.is_open();

        // Hold the last browser for the length of its exit.
        if self.browser.is_some() {
            self.browser_leaving = self.browser.clone();
        }

        let collect_text = self.browser.is_some() || self.renaming.is_some();
        // While a sentence is being spoken, or the letters are pitches,
        // Escape is the grammar's: it abandons the sentence or leaves
        // pitch entry, and only a bare Escape leaves the clip.
        let grammar_owns_escape =
            self.inside.is_some() && (!self.sentence.is_empty() || self.midi_typing.enabled());
        let scope = self.scope_context();
        let inputs = if palette_open {
            Vec::new()
        } else {
            ui.input_mut(|input| {
                let chords = keymap::consume_chords(input, scope, |modifiers, key| {
                    grammar_owns_escape
                        && modifiers == egui::Modifiers::NONE
                        && key == egui::Key::Escape
                });
                let pressed = |wanted: egui::Key| chords.iter().any(|(_, key)| *key == wanted);
                let questionmark_consumed = pressed(egui::Key::Questionmark);
                let space_consumed = pressed(egui::Key::Space);
                let mut stage_inputs: Vec<keymap::StageInput> = chords
                    .iter()
                    .map(|(modifiers, key)| keymap::StageInput::Chord(*modifiers, *key))
                    .collect();
                if collect_text {
                    for event in &input.events {
                        let egui::Event::Text(text) = event else {
                            continue;
                        };
                        // A physical '?' is the codebook chord. egui also emits
                        // it as text; admitting both would make one keystroke do
                        // two things. Pasted '?' remains ordinary filter text.
                        if questionmark_consumed && text == "?" {
                            continue;
                        }
                        // Space is a global transport chord even while the
                        // browser owns text. As with '?', admit the physical
                        // key exactly once while leaving pasted whitespace
                        // inside longer text untouched.
                        if space_consumed && text == " " {
                            continue;
                        }
                        stage_inputs.extend(text.chars().map(keymap::StageInput::Text));
                    }
                }
                stage_inputs
            })
        };

        // A refused keystroke is drawn, not swallowed: under key repeat
        // the refusal re-arrives every frame, so pressing against a limit
        // reads as a held mark on that limit rather than as a dead key.
        for input in inputs {
            let _ = self.handle_input(input);
        }

        // Inside a clip, the letters may be pitches. This runs before the
        // sequencer draws so a typed note enters on the frame it was
        // typed, and after the stage's own chords so `^T` is never read
        // as a T.
        self.entered_pitch = match self.inside {
            Some(opened) if self.scope_context() == keymap::ScopeContext::Clip => {
                let mode = self.entry_mode(opened);
                self.midi_typing
                    .update(ui.ctx(), mode)
                    .entered
                    .map(|entered| match entered {
                        midi_typing::Entered::Midi(midi) => Pitch::from_midi(midi),
                        midi_typing::Entered::Degree { degree, period } => {
                            Pitch::degree(degree, period)
                        }
                    })
            }
            _ => None,
        };

        // The view follows the cursor BEFORE anything is painted, so the
        // frame that shows a move has already scrolled to contain it —
        // never a frame late, which would read as the mark leaving the
        // strip and coming back.
        let field = Layout::of(ui.available_rect_before_wrap()).session;
        let addressed = self.session_address();
        self.strip_offset = tracks::offset_following(
            self.strip_offset,
            addressed.and_then(Address::track),
            self.song.tracks.len(),
            Self::strip_capacity(field),
        );
        // The scene axis follows only while the cursor is ON a scene: a
        // cursor on a head is not in any row, and must not drag the rows.
        let scene = match addressed {
            Some(Address::Slot { scene, .. }) => Some(scene),
            _ => None,
        };
        self.scene_offset = tracks::offset_following(
            self.scene_offset,
            scene,
            self.song.session.scenes.len(),
            Self::scene_capacity(field),
        );

        // The band's parameter rows follow the same minimal-scroll rule,
        // and ONE offset serves every column so the rows stay level
        // across devices — a list that scrolled per column would put two
        // different parameters on the same line and invite reading them
        // as a pair.
        if self.chain.is_some() {
            let (_, rows) = self.chain_shape();
            self.chain_offset = tracks::offset_following(
                self.chain_offset,
                self.chain
                    .as_ref()
                    .and_then(|lattice| lattice.cursor())
                    .map(|(_, row)| row),
                rows,
                Self::chain_capacity(Layout::of(ui.available_rect_before_wrap()).clip),
            );
        }

        // The clock. The engine's own position when the host read one
        // back this frame — so the playhead is what SOUNDED — and the
        // same fallback the legacy control plane uses when it did not:
        // the UI's stable frame delta, with continuous frames only while
        // time is actually passing.
        let dt = ui.ctx().input(|input| input.stable_dt);
        self.tick_clock(dt);
        if self.transport.motion().is_rolling() || self.meters.moving() || self.vitals.flashing() {
            ui.ctx().request_repaint();
        }

        self.draw(ui);
    }

    /// One frame of time. The engine's position, if the host read one
    /// back, or `dt` on the frame clock; and `dt` for everything that
    /// moves on its own between frames.
    fn tick_clock(&mut self, dt: f32) {
        self.frame_dt = dt;
        match self.engine_beat.take() {
            Some(beat) if self.transport.motion().is_rolling() => {
                self.transport.follow(beat);
            }
            _ => self.transport.advance(&self.song, f64::from(dt)),
        }
        self.vitals.tick(dt);
    }

    /// Where focus is standing, which is what every key is conditioned on.
    /// Draw the palette and run whatever was chosen.
    ///
    /// The list is the CURRENT scope's vocabulary — the same rows the
    /// codebook would show — so the palette answers "what can I press
    /// right now" rather than listing verbs that would be refused if
    /// picked.
    fn pump_palette(&mut self, ctx: &egui::Context) -> Option<StageIntent> {
        if !self.palette.is_open() {
            return None;
        }
        let scope = self.scope_context();
        let entries: Vec<&keymap::Entry> = keymap::palette_entries()
            .iter()
            .filter(|entry| entry.scope == scope)
            .collect();
        let commands: Vec<crate::ui::palette::Command> =
            entries.iter().map(|entry| entry.command).collect();
        // The palette is stock chrome, so it reads the runtime theme
        // rather than the alphabet — and it is handed the one that
        // matches the ground the stage is on, or it would be a dark
        // window over a paper page.
        let theme = match self.polarity {
            design::Polarity::Dark => crate::ui::theme::Theme::dark(),
            design::Polarity::Light => crate::ui::theme::Theme::light(),
        };
        let choice = self.palette.show(ctx, &theme, &commands, &[])?;
        let crate::ui::palette::Choice::Command(id) = choice else {
            // No long-form commands are offered here yet, so a typed line
            // has nothing to mean. Saying nothing is the honest answer.
            return None;
        };
        entries
            .iter()
            .find(|entry| entry.command.id == id)
            .map(|entry| entry.intent)
    }

    fn scope_context(&self) -> keymap::ScopeContext {
        if self.renaming.is_some() {
            keymap::ScopeContext::Rename
        } else if self.browser.is_some() {
            keymap::ScopeContext::Browser
        } else if self.chain.is_some() {
            keymap::ScopeContext::Chain
        } else if self.inside.is_some() {
            keymap::ScopeContext::Clip
        } else if self.mixing && self.focus.depth() == 1 {
            keymap::ScopeContext::Mixer
        } else if self.focus.depth() == 1 {
            keymap::ScopeContext::Root
        } else {
            keymap::ScopeContext::Nested
        }
    }

    /// The application's complete key path, shared by the headless sequence
    /// driver: keymap lookup, then intent application.
    #[cfg(test)]
    fn handle_key(&mut self, modifiers: egui::Modifiers, key: egui::Key) -> Option<ApplyOutcome> {
        self.handle_input(keymap::StageInput::Chord(modifiers, key))
    }

    fn handle_input(&mut self, input: keymap::StageInput) -> Option<ApplyOutcome> {
        let intent = keymap::dispatch(self.scope_context(), input)?;
        Some(self.apply(intent))
    }

    fn poll_library(&mut self, ctx: &egui::Context) {
        if let Some(snapshot) = self.library_service.newest_snapshot() {
            self.library_snapshot = snapshot;
            self.library_scanning = false;
            // The shelf is filled whether or not it happens to be open.
            // A tree keeps every shelf on screen, so "refresh only what is
            // being looked at" would leave a closed SAMPLES holding a
            // stale count that the reader can see.
            let nodes = sample_nodes(&self.library_snapshot.assets);
            if let Some(browser) = &mut self.browser {
                browser.set_children(Shelf::Samples, nodes, BrowserStatus::Ready);
            }
        }
        if self.library_scanning {
            ctx.request_repaint_after(std::time::Duration::from_millis(50));
        }
    }

    /// How many track columns the field can show. The strip's geometry is
    /// fixed by rule, so this is a pure function of the window and never of
    /// where the cursor stands.
    fn strip_capacity(field: egui::Rect) -> usize {
        let gap = column_gap();
        let margin = design::px(design::space::ROOM);
        // The master's column and the gap before it are not the strip's
        // to spend: a track drawn under the master would be a track the
        // performer cannot see.
        let usable = field.width() - margin * 2.0 - ADDRESS_W + gap - (TRACK_W + gap);
        if usable <= 0.0 {
            return 1;
        }
        ((usable / (TRACK_W + gap)).floor() as usize).max(1)
    }

    /// How many scene rows fit under the heads, and only whole ones.
    fn scene_capacity(field: egui::Rect) -> usize {
        let gap = row_gap();
        let margin = design::px(design::space::ROOM);
        let head_bottom = Self::head_rect(field, 0).max.y;
        scenes::rows_that_fit(field.max.y - margin - (head_bottom + section_gap()), gap)
    }

    /// The scenes the lattice currently shows, as a range into the
    /// session's rows. The vertical twin of [`Self::strip_window`].
    fn scene_window(&self, field: egui::Rect) -> std::ops::Range<usize> {
        let count = self.song.session.scenes.len();
        if count == 0 {
            return 0..0;
        }
        let first = self.scene_offset.min(count - 1);
        let last = first.saturating_add(Self::scene_capacity(field)).min(count);
        first..last
    }

    /// Where the cursor stands on the session, if it stands on it at all:
    /// `None` while focus is inside a track, in the browser, or the song
    /// has no tracks. Every question about "which track" or "which scene"
    /// the root cursor means is answered here and nowhere else.
    fn session_address(&self) -> Option<Address> {
        match self.focus.levels().first() {
            Some(FocusScope::Lattice(lattice)) => lattice
                .cursor()
                .map(|cursor| Address::of(cursor, self.song.tracks.len())),
            _ => None,
        }
    }

    /// The session as drawn: the root lattice, and the shade its cursor
    /// takes. The session is on screen whenever the cursor is on it OR
    /// inside a clip beneath it — the tray below is where focus went, and
    /// the session's cursor is then RESTING: where focus will land when
    /// it comes back, one rung down from where it is. Inside a TRACK
    /// (the calibration field) the session is not drawn at all.
    fn session_lattice(&self) -> Option<(&FocusLattice, egui::Color32)> {
        let FocusScope::Lattice(lattice) = self.focus.levels().first()? else {
            return None;
        };
        match (self.focus.depth(), self.inside) {
            (1, _) => Some((lattice, self.focused())),
            (_, Some(_)) => Some((lattice, self.resting())),
            _ => None,
        }
    }

    /// The session address only while the session is where the keyboard
    /// IS: not from inside a track, not from the browser. A verb on a
    /// slot must not fire on a cell the performer is not looking at.
    fn standing_on(&self) -> Option<Address> {
        (self.browser.is_none() && self.focus.depth() == 1)
            .then(|| self.session_address())
            .flatten()
    }

    /// The pitch language typed letters speak inside `opened`: the
    /// track's authority reads the ambient key, exactly as the second
    /// frame decides it. Local shadows global.
    fn entry_mode(&self, opened: Opened) -> midi_typing::EntryMode {
        match self
            .song
            .tracks
            .get(opened.track)
            .map(|track| track.pitch_authority)
        {
            Some(PitchAuthority::Degree) => midi_typing::EntryMode::Degree {
                degrees: self.song.key.degree_count(),
            },
            _ => midi_typing::EntryMode::Chromatic,
        }
    }

    /// The clip the tray shows: the one the cursor is INSIDE, or else the
    /// one the session cursor is resting on. A head or an empty slot
    /// shows nothing, and the tray goes quiet rather than showing a clip
    /// the cursor is not on.
    fn clip_in_view(&self) -> Option<Opened> {
        self.inside.or_else(|| match self.session_address()? {
            Address::Slot { track, scene } => {
                let Clip::Pattern(pattern) = self.song.slot_clip(track, scene)?;
                Some(Opened { pattern, track })
            }
            // Neither holds a clip: a head is a track's identity, and
            // the master is not a place clips live at all.
            Address::Head { .. } | Address::Master => None,
        })
    }

    /// The sequencer's edits land on the open pattern through the model's
    /// own applier — the one the second frame's bridge uses, so a nudge
    /// means the same thing in both frames. A refusal is kept for the
    /// message strip; a frame with no edits leaves the last one standing.
    fn apply_sequence(&mut self, id: PatternId, intents: &[sequence::Intent]) {
        if intents.is_empty() {
            return;
        }
        self.notice = self
            .song
            .pattern_mut(id)
            .and_then(|pattern| pattern.apply_all(intents))
            .map(str::to_owned);
        // An edit to a pattern changes what the launched scene sounds,
        // whether or not it was refused: a refusal leaves the pattern
        // alone, but working out which of a batch of intents landed is
        // the pattern's business and not this frame's.
        self.touched();
    }

    /// The tracks the strip currently shows, as a range into the song's
    /// order. `show` has already moved the window to contain the cursor,
    /// so drawing never decides where to look — it only draws what was
    /// decided. Everything that lines up under a head asks here, so the
    /// strip and the lattice can never disagree about which tracks are on
    /// screen.
    fn strip_window(&self, field: egui::Rect) -> std::ops::Range<usize> {
        let count = self.song.tracks.len();
        if count == 0 {
            return 0..0;
        }
        let first = self.strip_offset.min(count - 1);
        let last = first.saturating_add(Self::strip_capacity(field)).min(count);
        first..last
    }

    /// The head of the `slot`th shown track. The one place a column's
    /// geometry is decided: the lattice takes this rectangle and stacks
    /// beneath it, so a slot is the width of its head by construction
    /// rather than by agreement.
    /// The family mark a track wears: the sign its instrument is filed
    /// under in the browser, so one shape means one thing in both places.
    ///
    /// A track with no chain sounds the default voice, and says so with
    /// that voice's own sign rather than with nothing — silence about
    /// what a track is would be the one thing a head must never be.
    fn track_sigil(&self, track: usize) -> Option<glyph::Glyph> {
        let head = self.song.tracks.get(track)?;
        if head.kind == TrackKind::Audio {
            return Some(glyph::Glyph::Sample);
        }
        let kind = head
            .chain
            .first()
            .filter(|device| device.is_instrument())
            .map_or(crate::devices::DeviceKind::Poly, |device| device.kind);
        Some(browser::family_mark(kind.spec().family))
    }

    /// The master's column, pinned to the right edge of the field.
    ///
    /// It does NOT come from `head_rect`: every other column's place is a
    /// function of how far along the strip it is, and the master's whole
    /// point is that it is not along the strip at all. It belongs to the
    /// song rather than to anything in it, so it stays where the eye can
    /// always find it however many tracks scroll past.
    fn master_rect(field: egui::Rect) -> egui::Rect {
        let margin = design::px(design::space::ROOM);
        egui::Rect::from_min_size(
            egui::pos2(field.max.x - margin - TRACK_W, field.min.y + margin),
            egui::vec2(TRACK_W, TRACK_H),
        )
    }

    fn head_rect(field: egui::Rect, slot: usize) -> egui::Rect {
        let gap = column_gap();
        let margin = design::px(design::space::ROOM);
        egui::Rect::from_min_size(
            egui::pos2(
                field.min.x + margin + ADDRESS_W + slot as f32 * (TRACK_W + gap),
                field.min.y + margin,
            ),
            egui::vec2(TRACK_W, TRACK_H),
        )
    }

    /// Apply one semantic request to stage state. A refusal is both returned
    /// and retained in the frame channel; successful later intents do not
    /// erase it, so the slot always holds the latest refusal this frame.
    pub fn apply(&mut self, intent: StageIntent) -> ApplyOutcome {
        // A nudge waits exactly one intent for its direction. Whatever
        // comes next ends the wait: a Left or a Right is the motion, and
        // anything else is a sentence abandoned.
        let nudging = std::mem::take(&mut self.nudging);
        let result = match intent {
            StageIntent::Step(step @ (Step::Left | Step::Right)) if nudging => self.nudge(step),
            // While a name is being typed the keys are letters, and the
            // three that are not — keep, let go, erase — act on the name
            // and nothing else.
            StageIntent::Enter if self.renaming.is_some() => {
                let rename = self.renaming.take().expect("a rename is in flight");
                if self.song.rename_track(rename.track, &rename.text) {
                    self.notice = Some(format!("renamed to {}", rename.text.trim()));
                    Ok(())
                } else {
                    // A blank is refused and the rename stays open: the
                    // way to keep the old name is Escape, and the way to
                    // give a new one is to type it.
                    self.notice = Some("a track needs a name".to_owned());
                    self.renaming = Some(rename);
                    Err(RefusalReason::Empty)
                }
            }
            StageIntent::Escape if self.renaming.is_some() => {
                self.renaming = None;
                Ok(())
            }
            StageIntent::Backspace if self.renaming.is_some() => {
                let rename = self.renaming.as_mut().expect("a rename is in flight");
                if rename.fresh {
                    // The old name is the whole selection: one erase
                    // takes all of it.
                    rename.fresh = false;
                    let had = !rename.text.is_empty();
                    rename.text.clear();
                    had.then_some(()).ok_or(RefusalReason::Empty)
                } else {
                    rename.text.pop().map(|_| ()).ok_or(RefusalReason::Empty)
                }
            }
            StageIntent::TypeChar(ch) if self.renaming.is_some() => {
                let rename = self.renaming.as_mut().expect("a rename is in flight");
                if rename.fresh {
                    rename.text.clear();
                    rename.fresh = false;
                }
                rename.text.push(ch);
                Ok(())
            }
            // Movement goes wherever focus is standing. There is exactly
            // one cursor in the app, and this is the only place it moves.
            StageIntent::Step(step) if self.chain.is_some() => self
                .chain
                .as_mut()
                .expect("the band is showing")
                .step(step)
                .then_some(())
                .ok_or(RefusalReason::Edge(step)),
            StageIntent::Step(step) => match &mut self.browser {
                Some(browser) => browser
                    .step(step)
                    .then_some(())
                    .ok_or(if browser.is_empty() {
                        RefusalReason::Empty
                    } else {
                        RefusalReason::Edge(step)
                    }),
                None => self
                    .focus
                    .step(step)
                    .then_some(())
                    .ok_or(RefusalReason::Edge(step)),
            },
            // Making a track is a document edit. The strip is the scope
            // that STANDS FOR the document's tracks, so it follows the
            // song rather than being rebuilt beside it.
            StageIntent::NewAudioTrack | StageIntent::NewInstrumentTrack => {
                let kind = match intent {
                    StageIntent::NewAudioTrack => TrackKind::Audio,
                    _ => TrackKind::Instrument,
                };
                self.song.add_track(kind);
                self.fit_playing();
                self.touched();
                let last = self.song.tracks.len().saturating_sub(1);
                // Focus follows the new track only when the strip is where
                // the cursor is standing. From inside a track, moving an
                // ancestor's cursor would relocate a context the performer
                // is not looking at, and would land somewhere else on the
                // way back out.
                let standing_on_the_session = self.standing_on().is_some();
                if let FocusScope::Lattice(lattice) = self.focus.root_mut() {
                    lattice.resize_cols(last + 2);
                    if standing_on_the_session {
                        // The column changes; the row does not. A performer
                        // on scene four who makes a track is still on scene
                        // four, in the slot the new track just gave it.
                        lattice.focus_col(last);
                    }
                }
                Ok(())
            }
            StageIntent::Enter => match self
                .browser
                .as_ref()
                .and_then(Browser::selected)
                .map(|node| node.is_branch())
            {
                // A heading holds rows and does nothing else, so opening
                // it is the only thing pressing it could honestly mean.
                Some(true) => {
                    if let Some(browser) = &mut self.browser {
                        browser.toggle();
                    }
                    Ok(())
                }
                // A leaf is a thing to place. A device goes on the track
                // the cursor is standing in — the browser is a place
                // beside the session rather than a level inside it, so
                // the session's cursor never moved and still says which
                // track is being worked on.
                Some(false) => {
                    let leaf = self
                        .browser
                        .as_ref()
                        .and_then(Browser::selected)
                        .map(|node| node.kind.clone());
                    match (leaf, self.addressed_track()) {
                        (Some(EntryKind::Device(kind)), Some(track)) => {
                            match self.song.add_device(track, kind) {
                                Some(_) => {
                                    self.notice = Some(format!("+ {}", kind.spec().name));
                                    self.touched();
                                    Ok(())
                                }
                                // The one refusal `add_device` makes: an
                                // instrument offered to an audio track,
                                // whose sound comes from its clips.
                                None => Err(RefusalReason::Unavailable),
                            }
                        }
                        // A sound goes into a sampler: the one already at
                        // the head of the track, or a new one made for it.
                        (Some(EntryKind::Sample(path)), Some(track)) => {
                            self.place_sample(track, path)
                        }
                        // A song replaces this one. The browser closes
                        // with it — it was a window over the old song.
                        (Some(EntryKind::Project(path)), _) => match self.open(path) {
                            Ok(()) => {
                                self.browser = None;
                                Ok(())
                            }
                            Err(error) => {
                                self.notice = Some(format!("could not open: {error}"));
                                Err(RefusalReason::Unavailable)
                            }
                        },
                        _ => Err(RefusalReason::Unavailable),
                    }
                }
                None if self.browser.is_some() => Err(RefusalReason::Empty),
                // Going into a FILLED slot opens its pattern: the step
                // grid, sixteen by four. Going into an empty slot makes it
                // a place first — a new, empty pattern lands there — and
                // the next Enter opens it. An audio slot has no pattern
                // to take and is refused.
                None => match self.standing_on() {
                    Some(Address::Slot { track, scene }) => {
                        match self.song.slot_clip(track, scene) {
                            Some(Clip::Pattern(pattern)) => {
                                // The level mirrors the sequencer's own
                                // sixteen-by-four cursor, for the breadcrumb.
                                let entered = self
                                    .focus
                                    .enter(FocusScope::grid(PATTERN_COLS, PATTERN_ROWS));
                                if entered {
                                    self.inside = Some(Opened { pattern, track });
                                }
                                entered.then_some(()).ok_or(RefusalReason::Deeper)
                            }
                            None => {
                                let filled = self.song.fill_slot(track, scene).is_some();
                                if filled {
                                    self.touched();
                                }
                                filled.then_some(()).ok_or(RefusalReason::Unavailable)
                            }
                        }
                    }
                    // Inside a clip the sequencer's grammar owns Enter (it
                    // is ACT there); the stage never binds it, and refuses
                    // it if asked directly.
                    _ if self.inside.is_some() => Err(RefusalReason::Unavailable),
                    _ => self
                        .focus
                        .enter(FocusScope::grid(GRID_COLS, GRID_ROWS))
                        .then_some(())
                        .ok_or(RefusalReason::Deeper),
                },
            },
            // Clearing is a slot's verb and nothing else's: on a head, from
            // inside a track, or in the browser there is nothing it could
            // honestly mean. An empty slot is not an error, but it is not
            // a change either, and says so.
            StageIntent::Clear if self.chain.is_some() => match self.chained_device() {
                Some((track, device)) => {
                    let id = self.song.tracks[track].chain[device].id;
                    let taken = self.song.remove_device(track, id);
                    self.notice = taken
                        .as_ref()
                        .map(|device| format!("- {}", device.kind.spec().name));
                    // The band is one device narrower; the cursor comes
                    // back inside it rather than pointing past the end.
                    let (cols, rows) = self.chain_shape();
                    match (cols, self.chain.as_mut()) {
                        (0, _) => self.chain = None,
                        (_, Some(lattice)) => {
                            lattice.resize_cols(cols);
                            lattice.resize_rows(rows);
                        }
                        _ => {}
                    }
                    self.touched();
                    taken.map(|_| ()).ok_or(RefusalReason::Empty)
                }
                None => Err(RefusalReason::Empty),
            },
            StageIntent::Clear => match self.standing_on() {
                Some(Address::Slot { track, scene }) => {
                    let cleared = self.song.clear_slot(track, scene).is_some();
                    if cleared {
                        self.touched();
                    }
                    cleared.then_some(()).ok_or(RefusalReason::Empty)
                }
                _ => Err(RefusalReason::Unavailable),
            },
            // Escape is one meaning everywhere: up and OUT. It leaves
            // whatever is outermost — the codebook first, then the
            // browser, then a scope.
            StageIntent::Escape => {
                if self.help {
                    self.help = false;
                    Ok(())
                } else if self.chain.is_some() {
                    // The band is a place focus went to, so leaving it is
                    // leaving the outermost thing — the same meaning
                    // Escape has everywhere.
                    self.chain = None;
                    Ok(())
                } else if self.mixing {
                    // Escape leaves the outermost thing, and while the
                    // mixer is up that is the mixer.
                    self.mixing = false;
                    if let FocusScope::Lattice(lattice) = self.focus.root_mut() {
                        lattice.resize_rows(scenes::lattice_rows(&self.song));
                    }
                    Ok(())
                } else if self.browser.is_some() {
                    // Climbing the tree is Left's job now. Escape keeps
                    // its one meaning — leave the outermost thing — and
                    // never doubles as a second, quieter way to move.
                    self.browser = None;
                    Ok(())
                } else {
                    let left = self.focus.escape();
                    // Leaving the step grid leaves the pattern behind: the
                    // id is only meaningful while a level stands for it.
                    if left && self.focus.depth() == 1 {
                        self.inside = None;
                        self.notice = None;
                    }
                    left.then_some(()).ok_or(RefusalReason::Shallower)
                }
            }
            StageIntent::ToggleTransport => {
                match self.transport.motion() {
                    Motion::Stopped => self.transport.set_motion(Motion::Rolling),
                    // Space is the shortest emergency path out of a write;
                    // it never silently demotes recording into ordinary roll.
                    Motion::Rolling | Motion::Recording => self.transport.stop(),
                }
                Ok(())
            }
            StageIntent::Rewind => {
                let before = self.transport;
                self.transport.rewind();
                if self.transport == before {
                    Err(RefusalReason::AtTop)
                } else {
                    // The stage moved its own clock; the host has to move
                    // the engine's to match, and this is how it knows.
                    self.seeks = self.seeks.wrapping_add(1);
                    Ok(())
                }
            }
            StageIntent::Help => {
                self.help = !self.help;
                Ok(())
            }
            // Firing a scene changes no document: it says which row the
            // performance is on. Firing the row already playing stops it,
            // so the one gesture is its own undo.
            // ONE clip: the track it is on plays it, and every other
            // track carries on with whatever it was already playing.
            StageIntent::Launch => match self.standing_on() {
                Some(Address::Slot { track, scene }) => {
                    self.fit_playing();
                    let Some(slot) = self.playing.get_mut(track) else {
                        return ApplyOutcome::Refused(Refusal {
                            intent,
                            reason: RefusalReason::Unavailable,
                        });
                    };
                    // Firing what is already playing stops it, so the one
                    // gesture is its own undo.
                    *slot = (*slot != Some(scene)).then_some(scene);
                    self.touched();
                    Ok(())
                }
                // A head is a track, not a place a clip lives.
                _ => Err(RefusalReason::Unavailable),
            },
            // The whole ROW: every track takes that scene's clip, and a
            // track with nothing in that scene falls silent — which is
            // what firing a row means rather than a special case of it.
            StageIntent::LaunchScene => match self.standing_on() {
                Some(Address::Slot { scene, .. }) => {
                    self.fit_playing();
                    let already = self.playing.iter().all(|slot| *slot == Some(scene));
                    for slot in &mut self.playing {
                        *slot = (!already).then_some(scene);
                    }
                    self.touched();
                    Ok(())
                }
                _ => Err(RefusalReason::Unavailable),
            },
            // The fader. Refused at either end of its travel, in the
            // same words a cursor is refused at the edge of a grid:
            // there is no next place in that direction.
            // The master's own fader, when the cursor is on its column.
            StageIntent::Gain { louder, fine } if self.standing_on() == Some(Address::Master) => {
                let size = if fine {
                    mixer::GAIN_FINE_DB
                } else {
                    mixer::GAIN_STEP_DB
                };
                let step = if louder { size } else { -size };
                let before = self.song.master;
                self.song.master = mixer::step_gain(before, step);
                self.notice = Some(mixer::gain_label(self.song.master));
                let moved = self.song.master != before;
                if moved {
                    self.remixed();
                }
                moved.then_some(()).ok_or(RefusalReason::Edge(if louder {
                    Step::Up
                } else {
                    Step::Down
                }))
            }
            StageIntent::Gain { louder, fine } => match self.focused_track() {
                Some(index) => {
                    let size = if fine {
                        mixer::GAIN_FINE_DB
                    } else {
                        mixer::GAIN_STEP_DB
                    };
                    let step = if louder { size } else { -size };
                    let track = &mut self.song.tracks[index];
                    let before = track.volume;
                    track.volume = mixer::step_gain(before, step);
                    let moved = track.volume != before;
                    self.notice = Some(mixer::gain_label(self.song.tracks[index].volume));
                    if moved {
                        self.remixed();
                    }
                    moved.then_some(()).ok_or(RefusalReason::Edge(if louder {
                        Step::Up
                    } else {
                        Step::Down
                    }))
                }
                None => Err(RefusalReason::Unavailable),
            },
            StageIntent::Pan { right } => match self.focused_track() {
                Some(index) => {
                    let step = if right {
                        mixer::PAN_STEP
                    } else {
                        -mixer::PAN_STEP
                    };
                    let track = &mut self.song.tracks[index];
                    let before = track.pan;
                    track.pan = mixer::step_pan(before, step);
                    let moved = track.pan != before;
                    self.notice = Some(mixer::pan_label(self.song.tracks[index].pan));
                    if moved {
                        self.remixed();
                    }
                    moved.then_some(()).ok_or(RefusalReason::Edge(if right {
                        Step::Right
                    } else {
                        Step::Left
                    }))
                }
                None => Err(RefusalReason::Unavailable),
            },
            // The switches change AUDIBILITY, which is what decides who
            // reaches the graph at all — so unlike a fader these are a
            // rebuild rather than a letter.
            StageIntent::Mute if self.chain.is_some() => match self.chained_device() {
                Some((track, device)) => {
                    let lane = &mut self.song.tracks[track].chain[device];
                    lane.bypassed = !lane.bypassed;
                    let bypassed = lane.bypassed;
                    self.notice = Some(if bypassed { "bypassed" } else { "in" }.to_owned());
                    // Bypass changes who is in the graph at all, so the
                    // graph is rebuilt — the same division a track's mute
                    // makes against a fader.
                    self.touched();
                    Ok(())
                }
                None => Err(RefusalReason::Empty),
            },
            StageIntent::Mute => match self.focused_track() {
                Some(index) => {
                    self.song.tracks[index].muted = !self.song.tracks[index].muted;
                    self.notice = Some(
                        if self.song.tracks[index].muted {
                            "muted"
                        } else {
                            "unmuted"
                        }
                        .to_owned(),
                    );
                    self.touched();
                    Ok(())
                }
                None => Err(RefusalReason::Unavailable),
            },
            StageIntent::Solo => match self.focused_track() {
                Some(index) => {
                    self.song.tracks[index].solo = !self.song.tracks[index].solo;
                    self.notice = Some(
                        if self.song.tracks[index].solo {
                            "soloed"
                        } else {
                            "unsoloed"
                        }
                        .to_owned(),
                    );
                    self.touched();
                    Ok(())
                }
                None => Err(RefusalReason::Unavailable),
            },
            // Summoning the band takes focus with it, exactly as the
            // browser does; dismissing gives focus back to the session,
            // whose cursor was never touched.
            StageIntent::Devices => {
                if self.chain.is_some() {
                    self.chain = None;
                    Ok(())
                } else {
                    let (cols, rows) = self.chain_shape();
                    if cols == 0 {
                        // A track with no devices has no band to show. Not
                        // an error to ask — there is nothing there yet,
                        // which is what Empty says.
                        Err(RefusalReason::Empty)
                    } else {
                        self.chain = Some(FocusLattice::new(cols, rows));
                        self.chain_offset = 0;
                        Ok(())
                    }
                }
            }
            StageIntent::Param { up, coarse } => match self.chained_param() {
                Some((track, device, param)) => {
                    let spec = self.song.tracks[track].chain[device].kind.spec();
                    match spec
                        .params
                        .iter()
                        .zip(spec.labels)
                        .find(|(def, _)| def.id == param)
                    {
                        None => Err(RefusalReason::Unavailable),
                        Some((def, label)) => {
                            let step =
                                chain::step_of(def, label, coarse) * if up { 1.0 } else { -1.0 };
                            let name = label.name;
                            let lane = &mut self.song.tracks[track].chain[device];
                            let before = lane.value(param);
                            lane.set(param, before + step);
                            let after = lane.value(param);
                            self.notice =
                                Some(format!("{name} {}", chain::format_param(def, label, after)));
                            if after == before {
                                // The end of the range, said the way the
                                // edge of a grid is said.
                                Err(RefusalReason::Edge(if up { Step::Up } else { Step::Down }))
                            } else {
                                // A parameter rides a LETTER to a node
                                // already running, exactly as a fader
                                // does — the chain does not rebuild
                                // because somebody turned something.
                                self.remixed();
                                Ok(())
                            }
                        }
                    }
                }
                None => Err(RefusalReason::Unavailable),
            },
            StageIntent::Ground => {
                self.polarity = match self.polarity {
                    design::Polarity::Dark => design::Polarity::Light,
                    design::Polarity::Light => design::Polarity::Dark,
                };
                Ok(())
            }
            StageIntent::Mix => {
                self.mixing = !self.mixing;
                // The lattice keeps its columns and changes its height:
                // the scenes are a row each, while a channel is addressed
                // as ONE thing. The cursor's column survives, which is
                // what makes the switch keep the performer's place.
                let rows = if self.mixing {
                    1
                } else {
                    scenes::lattice_rows(&self.song)
                };
                if let FocusScope::Lattice(lattice) = self.focus.root_mut() {
                    lattice.resize_rows(rows);
                }
                Ok(())
            }
            // Summoning the browser takes focus with it; dismissing gives
            // focus back exactly where it was, because the field's cursor
            // was never touched.
            StageIntent::Browse => {
                self.browser = match self.browser {
                    Some(_) => None,
                    // The library opens at its shelves. The samples are
                    // not scanned yet; the songs are read from the songs
                    // folder now, because a folder is not a scan.
                    None => {
                        let mut browser = Browser::shelves();
                        browser.set_children(
                            Shelf::Projects,
                            browser::project_nodes(self.home.as_deref()),
                            if self.home.is_some() {
                                BrowserStatus::Ready
                            } else {
                                BrowserStatus::Unavailable
                            },
                        );
                        Some(browser)
                    }
                };
                Ok(())
            }
            StageIntent::TypeChar(ch) => self
                .browser
                .as_mut()
                .map(|browser| browser.type_char(ch))
                .ok_or(RefusalReason::Unavailable),
            StageIntent::Backspace => self
                .browser
                .as_mut()
                .ok_or(RefusalReason::Unavailable)
                .and_then(|browser| {
                    browser
                        .backspace()
                        .then_some(())
                        .ok_or(RefusalReason::Empty)
                }),
            // History. The floor refuses quietly and says so; a step
            // that lands leaves focus where it is and the performance
            // running, because undoing a fader move is not a reason to
            // stop the song or lose one's place.
            StageIntent::Undo => {
                let mut song = self.song.clone();
                if self.history.undo(&mut song) {
                    self.adopt_song(song);
                    self.dirty = true;
                    self.notice = Some("undo".to_owned());
                    Ok(())
                } else {
                    self.notice = Some("nothing to undo".to_owned());
                    Err(RefusalReason::Empty)
                }
            }
            StageIntent::Redo => {
                let mut song = self.song.clone();
                if self.history.redo(&mut song) {
                    self.adopt_song(song);
                    self.dirty = true;
                    self.notice = Some("redo".to_owned());
                    Ok(())
                } else {
                    self.notice = Some("nothing to redo".to_owned());
                    Err(RefusalReason::Empty)
                }
            }
            StageIntent::Save => match self.save() {
                Ok(()) => Ok(()),
                Err(error) => {
                    self.notice = Some(format!("could not save: {error}"));
                    Err(RefusalReason::Unavailable)
                }
            },
            // The track under the cursor. Its name is typed over the head
            // it belongs to; taking it out of the song takes its slots
            // with it, and the last track stays — a session with no
            // columns has nowhere for the cursor to be.
            StageIntent::Rename => match self.focused_track() {
                Some(index) => {
                    self.renaming = Some(Rename {
                        track: index,
                        text: self.song.tracks[index].name.clone(),
                        fresh: true,
                    });
                    Ok(())
                }
                None => Err(RefusalReason::Unavailable),
            },
            StageIntent::DeleteTrack => self.delete_track(),
            StageIntent::Nudge => {
                // Only where there is something to move. Spoken from the
                // browser or inside a clip it would wait for a motion
                // that could not mean anything.
                if self.chained_device().is_some() || self.focused_track().is_some() {
                    self.nudging = true;
                    self.notice = Some("NUDGE · ← →".to_owned());
                    Ok(())
                } else {
                    Err(RefusalReason::Unavailable)
                }
            }
            StageIntent::Yank => self.yank(),
            StageIntent::Put => self.put(),
        };
        // Every intent ends at a settled song, which is what undo steps
        // back through. Undo and redo settle where they land, so the
        // observation is a no-op for them.
        self.settle();
        match result {
            Ok(()) => ApplyOutcome::Changed,
            Err(reason) => {
                let refusal = Refusal { intent, reason };
                self.refusal = Some(refusal);
                ApplyOutcome::Refused(refusal)
            }
        }
    }

    /// A nudge's motion: the device under the band's cursor one place
    /// along its chain, or the track under the session's cursor one
    /// place along the strip. The cursor goes with the thing it moved,
    /// so a second press moves it again.
    fn nudge(&mut self, step: Step) -> Result<(), RefusalReason> {
        let later = step == Step::Right;
        if self.chain.is_some() {
            let (track, device) = self.chained_device().ok_or(RefusalReason::Empty)?;
            let id = self.song.tracks[track].chain[device].id;
            if !self.song.move_device(track, id, later) {
                return Err(RefusalReason::Edge(step));
            }
            let to = self.song.tracks[track]
                .chain
                .iter()
                .position(|candidate| candidate.id == id)
                .unwrap_or(device);
            if let Some(lattice) = self.chain.as_mut() {
                lattice.focus_col(to);
            }
            self.notice = Some(format!(
                "{} → {}",
                self.song.tracks[track].chain[to].kind.spec().name,
                to + 1
            ));
            self.touched();
            return Ok(());
        }
        let index = self.focused_track().ok_or(RefusalReason::Unavailable)?;
        if !self.song.move_track(index, later) {
            return Err(RefusalReason::Edge(step));
        }
        let to = if later { index + 1 } else { index - 1 };
        // What each track is playing is indexed by position, and the
        // positions just swapped.
        self.fit_playing();
        self.playing.swap(index, to);
        if let FocusScope::Lattice(lattice) = self.focus.root_mut() {
            lattice.focus_col(to);
        }
        self.notice = Some(format!("{} → {:02}", self.song.tracks[to].name, to + 1));
        self.touched();
        Ok(())
    }

    /// Lift the device under the band's cursor off its chain and keep it,
    /// settings and all.
    fn yank(&mut self) -> Result<(), RefusalReason> {
        let (track, device) = self.chained_device().ok_or(RefusalReason::Empty)?;
        let id = self.song.tracks[track].chain[device].id;
        let taken = self
            .song
            .remove_device(track, id)
            .ok_or(RefusalReason::Empty)?;
        self.notice = Some(format!("yanked {}", taken.kind.spec().name));
        self.clipboard = Some(taken);
        self.fit_session();
        self.touched();
        Ok(())
    }

    /// Put the kept device down: after the device under the band's
    /// cursor, or at the end of the addressed track's chain when the band
    /// is not up. The clipboard keeps it, so one device can go on several
    /// tracks — each copy with an id of its own.
    fn put(&mut self) -> Result<(), RefusalReason> {
        let device = self.clipboard.clone().ok_or(RefusalReason::Empty)?;
        let track = self.addressed_track().ok_or(RefusalReason::Unavailable)?;
        let at = match self.chained_device() {
            Some((_, index)) => index + 1,
            None => self.song.tracks[track].chain.len(),
        };
        let name = device.kind.spec().name;
        let id = self
            .song
            .insert_device(track, at, device)
            .ok_or(RefusalReason::Unavailable)?;
        self.notice = Some(format!("+ {name}"));
        self.fit_session();
        if let Some(lattice) = self.chain.as_mut() {
            let to = self.song.tracks[track]
                .chain
                .iter()
                .position(|candidate| candidate.id == id)
                .unwrap_or(0);
            lattice.focus_col(to);
        }
        self.touched();
        Ok(())
    }

    /// Take the track under the cursor out of the song. The cursor stays
    /// at the same place on the strip, which is now the next track along
    /// — or the last one, if it was the last that went.
    fn delete_track(&mut self) -> Result<(), RefusalReason> {
        let index = self.focused_track().ok_or(RefusalReason::Unavailable)?;
        if self.song.tracks.len() <= 1 {
            self.notice = Some("the last track stays".to_owned());
            return Err(RefusalReason::Unavailable);
        }
        let removed = self
            .song
            .remove_track(index)
            .ok_or(RefusalReason::Unavailable)?;
        if index < self.playing.len() {
            self.playing.remove(index);
        }
        self.notice = Some(format!("- {}", removed.name));
        self.fit_session();
        let last = self.song.tracks.len() - 1;
        if let FocusScope::Lattice(lattice) = self.focus.root_mut() {
            lattice.focus_col(index.min(last));
        }
        self.touched();
        Ok(())
    }

    /// A sound for the addressed track: into the sampler at its head, or
    /// into a new sampler that takes the head. An audio track has no
    /// instrument to give a sound to, and says so.
    fn place_sample(&mut self, track: usize, path: PathBuf) -> Result<(), RefusalReason> {
        let name = path
            .file_name()
            .map(|name| name.to_string_lossy().into_owned())
            .unwrap_or_default();
        let head_is_sampler = self.song.tracks[track]
            .chain
            .first()
            .is_some_and(|device| device.kind == DeviceKind::Sampler);
        let id = if head_is_sampler {
            self.song.tracks[track].chain[0].id
        } else {
            self.song
                .add_device(track, DeviceKind::Sampler)
                .ok_or(RefusalReason::Unavailable)?
        };
        if let Some(device) = self.song.device_mut(id) {
            device.sample = Some(path);
        }
        self.notice = Some(format!("+ sampler · {name}"));
        self.fit_session();
        self.touched();
        Ok(())
    }

    fn draw(&mut self, ui: &mut egui::Ui) {
        let whole = ui.available_rect_before_wrap();
        let painter = ui.painter().clone();

        // The constitution: a thin fixed periphery around one sovereign
        // field. The strips hold display only; nothing in them is ever
        // focusable, and their geometry never changes.
        let Layout {
            vitals,
            breadcrumb,
            transport,
            message,
            browser,
            field,
            session,
            clip,
        } = Layout::of(whole);

        // Separation is a STEP IN VALUE, not a rule drawn between things.
        // Two planes that differ in lightness are already divided; a line
        // laid along the seam restates a boundary the eye has read, and a
        // screen full of restatements is the noise floor this surface
        // spends its budget keeping down.
        //
        // The consequence is worth the trade: a stroke now always MEANS
        // something. Every line left on this surface is a sign — a gate, a
        // refusal, the signature — and none of them is furniture.
        // The frame paints its OWN ground first.
        //
        // It used to rely on the host's clear colour being the same one,
        // which held only as long as the two agreed — and the moment the
        // ground became switchable that agreement was a thing to get
        // wrong rather than a constant. A surface that is only the right
        // colour when somebody else guessed correctly is not a surface
        // that owns its own appearance.
        painter.rect_filled(whole, 0.0, self.alphabet().ground.color);
        // The ground's own material. Quietest thing on the surface, says
        // nothing, and therefore may cover everything — and what it does
        // say without saying it is that this app is a lattice.
        ornament::lattice(
            &painter,
            field,
            self.alphabet().surface.color,
            design::px(design::space::VAST),
        );
        painter.rect_filled(vitals, 0.0, self.alphabet().surface.color);
        painter.rect_filled(message, 0.0, self.alphabet().surface.color);
        // The regions get an edge each.
        //
        // This is a DEPARTURE from the rule above, and worth saying so
        // rather than quietly breaking it: value alone divides two planes
        // well on a black ground, where the resting rungs sit against
        // nothing. On PAPER the same rungs are three steps inside a
        // narrow band near white, and a seam between two of them is a
        // difference the eye has to look for. The line is doing work the
        // value cannot do here, which is the test any mark on this
        // surface has to pass.
        //
        // It is the structure rung and one pixel: enough to bound a
        // region, not enough to become the thing you see first.
        // The browser is NOT bounded here. Its rectangle overlaps the
        // session's, so an edge around it while it is away is a line
        // through the middle of something else — and while it is
        // arriving, an edge drawn at the destination is a line the
        // panel has not reached yet. Its edge travels with it, in the
        // slide below.
        for region in [vitals, message, session, clip] {
            painter.rect_stroke(
                region,
                0.0,
                egui::Stroke::new(1.0, self.alphabet().edge.color),
                egui::StrokeKind::Inside,
            );
        }

        self.draw_breadcrumb(&painter, breadcrumb);
        self.draw_engine(&painter, message);
        self.draw_transport(&painter, transport);
        // The badge. Instruments have them, and this is the one piece of
        // ornament here that carries nothing at all.
        ornament::sigil(
            &painter,
            egui::pos2(
                message.min.x + design::px(design::space::ROOM),
                message.center().y,
            ),
            design::px(design::space::STEP) / 2.0,
            self.alphabet().edge.color,
        );
        self.draw_message(&painter, message);
        // The codebook takes the whole field while it is up. It is a
        // DISPLAY mode, not a scope: focus never enters it, and the
        // cursor underneath is exactly where it was left.
        if self.help {
            self.draw_help(&painter, field);
        } else {
            // Stacked: the session above, the clip tray below. The tray
            // shows whatever clip the session cursor is on, and is only
            // FOCUSED once entered — Ableton's session over its clip
            // detail, an Elektron's track keys over its trig keys.
            self.draw_field(&painter, session);
            // One detail region, and the band and the sequencer are two
            // things to put in it. The band wins while it is showing:
            // sound design and sequencing are separate spaces, and the
            // one you are in is the one you asked for.
            if self.chain.is_some() {
                self.draw_chain(ui.painter(), clip);
            } else {
                self.draw_clip(ui, clip);
            }
        }
        // Last, and over the top of everything in the field: the browser
        // is a window above the work, not a division of it.
        //
        // It SLIDES, from the edge it belongs to. Motion here is not
        // decoration: a panel that simply appears has to be found, while
        // one that arrives from somewhere has already told the eye where
        // it came from and where it will go back to.
        let open = ui.ctx().animate_bool_with_time(
            egui::Id::new("stage-browser-slide"),
            self.browser.is_some(),
            BROWSER_SLIDE_S,
        );
        if open > 0.0 && self.browser_leaving.is_some() {
            let slid = browser.translate(egui::vec2(-browser.width() * (1.0 - open), 0.0));
            // Clipped to the field, so the part that has not arrived is
            // not drawn over the periphery on its way in.
            let painter = painter.with_clip_rect(field);
            self.draw_browser(&painter, slid);
            // Its own edge, at wherever it has got to. Drawn with the
            // panel rather than with the other regions: a border that
            // waited at the destination would announce the arrival
            // before the thing arrived.
            painter.rect_stroke(
                slid,
                0.0,
                egui::Stroke::new(1.0, self.alphabet().edge.color),
                egui::StrokeKind::Inside,
            );
        }
    }

    /// The clip tray. The sequencer draws the clip in view — the stage
    /// builds what it reads (notes resolved against the key, the track's
    /// lens) — and has the keys only while the cursor is inside. While
    /// focus is elsewhere the tray is drawn and then veiled, so the
    /// sequencer's own white stays below the one focus-bright thing on
    /// the screen, and lands whatever it asked for on the pattern.
    /// The chain band: the addressed track's devices, in signal order,
    /// each carrying its whole parameter table as a scrolling list.
    fn draw_chain(&self, painter: &egui::Painter, tray: egui::Rect) {
        let Some(lattice) = self.chain.as_ref() else {
            return;
        };
        let Some(track) = self.addressed_track() else {
            return;
        };
        let columns = chain::columns(&self.song, track);
        if columns.is_empty() {
            return;
        }
        let alpha = self.alphabet();
        let margin = design::px(design::space::ROOM);
        let pad = design::px(design::space::SNUG);
        let gap = column_gap();
        let title_font = egui::FontId::monospace(design::px(design::type_scale::MICRO));
        let row_font = egui::FontId::monospace(design::px(design::type_scale::MICRO));

        let head_h = design::px(design::space::OPEN);
        let pitch = design::px(design::space::ROOM);
        let body_top = tray.min.y + head_h;
        let rows_shown = chain::rows_that_fit(tray.max.y - margin - body_top, pitch);
        let cursor = lattice.cursor();
        // The column is monospace, so its width is a COUNT of cells — and
        // a name laid out without knowing that count runs straight into
        // the value at its right. One measurement, once.
        let cell_w = painter
            .layout_no_wrap("M".to_owned(), row_font.clone(), alpha.ink.color)
            .rect
            .width()
            .max(1.0);
        let cells = ((TRACK_W - pad * 2.0) / cell_w).floor().max(1.0) as usize;

        for (index, column) in columns.iter().enumerate() {
            let x = tray.min.x + margin + index as f32 * (TRACK_W + gap);
            if x + TRACK_W > tray.max.x {
                break;
            }
            let head =
                egui::Rect::from_min_size(egui::pos2(x, tray.min.y), egui::vec2(TRACK_W, head_h));
            let here = cursor.map(|(col, _)| col) == Some(index);

            // The device's own head: its name, and whether it is passing
            // sound through. A bypassed device keeps its place and its
            // list — it is drawn at the structure rung instead of the
            // content one, which is the same step down the ladder a
            // silenced thing takes everywhere on this surface.
            ornament::plane(
                painter,
                head,
                if here {
                    alpha.edge.color
                } else {
                    alpha.surface.color
                },
                Some(ornament::Cut::TopLeft),
            );
            if here {
                ornament::brackets(painter, head.expand(2.0), alpha.ink.color, 1.0, 6.0);
            }
            let ink = if column.bypassed {
                alpha.edge.color
            } else {
                alpha.ink.color
            };
            painter.text(
                egui::pos2(head.min.x + pad, head.center().y),
                egui::Align2::LEFT_CENTER,
                column.title,
                title_font.clone(),
                if here { alpha.ground.color } else { ink },
            );
            // The right of the head: the bypass mark, or — on a sampler
            // that is not bypassed — the name of the file it plays, cut
            // to the cells the title leaves free.
            let aside = if column.bypassed {
                Some("—".to_owned())
            } else {
                column.sample.as_ref().map(|name| {
                    let room = cells.saturating_sub(column.title.chars().count() + 1);
                    name.chars().take(room).collect()
                })
            };
            if let Some(aside) = aside {
                painter.text(
                    egui::pos2(head.max.x - pad, head.center().y),
                    egui::Align2::RIGHT_CENTER,
                    aside,
                    title_font.clone(),
                    if here {
                        alpha.ground.color
                    } else {
                        alpha.ink.color
                    },
                );
            }

            // Its parameters, from the scroll offset down. A name at the
            // left and a value at the right, both monospace, so the
            // values form a column the eye reads without tracking.
            for line in 0..rows_shown {
                let Some(row) = column.rows.get(self.chain_offset + line) else {
                    break;
                };
                let top = body_top + line as f32 * pitch;
                let rect =
                    egui::Rect::from_min_size(egui::pos2(x, top), egui::vec2(TRACK_W, pitch));
                let on_row = cursor == Some((index, self.chain_offset + line));
                if on_row {
                    painter.rect_filled(rect, 0.0, alpha.edge.color);
                }
                // An edited value carries the content rung; one still at
                // its default is structure. That is the one distinction a
                // list of forty numbers cannot otherwise make.
                let (name_ink, value_ink) = if on_row {
                    (alpha.ground.color, alpha.ground.color)
                } else if row.edited {
                    (alpha.edge.color, alpha.ink.color)
                } else {
                    (alpha.edge.color, alpha.edge.color)
                };
                // The value keeps its cells and the name takes what is
                // left, with one cell of air between. A name too long for
                // its column is cut rather than allowed to run under the
                // number — a truncated word is still readable, and two
                // overlapping ones are not.
                let room = cells.saturating_sub(row.value.chars().count() + 1);
                painter.text(
                    egui::pos2(rect.min.x + pad, rect.center().y),
                    egui::Align2::LEFT_CENTER,
                    fit_cells(&row.name, room),
                    row_font.clone(),
                    name_ink,
                );
                // The oldest fix for the oldest problem in a list: a
                // name at one edge, its value at the other, and a run of
                // points so the eye crosses without losing the row.
                if !on_row {
                    let name_end =
                        rect.min.x + pad + row.name.chars().count().min(room) as f32 * cell_w;
                    let value_start = rect.max.x - pad - row.value.chars().count() as f32 * cell_w;
                    ornament::leaders(
                        painter,
                        name_end + cell_w,
                        value_start - cell_w,
                        rect.center().y,
                        alpha.edge.color,
                        cell_w,
                    );
                }
                painter.text(
                    egui::pos2(rect.max.x - pad, rect.center().y),
                    egui::Align2::RIGHT_CENTER,
                    &row.value,
                    row_font.clone(),
                    value_ink,
                );
            }

            // More parameters below than the band is showing: a point at
            // the foot, the same mark an empty session slot uses, because
            // it means the same thing — there is something here.
            if column.rows.len() > self.chain_offset + rows_shown {
                painter.rect_filled(
                    egui::Rect::from_center_size(
                        egui::pos2(head.center().x, tray.max.y - margin / 2.0),
                        egui::Vec2::splat(POINT),
                    ),
                    0.0,
                    alpha.ink.color,
                );
            }
        }
    }

    fn draw_clip(&mut self, ui: &mut egui::Ui, tray: egui::Rect) {
        let Some(shown) = self.clip_in_view() else {
            return;
        };
        let Some(pattern) = self.song.pattern(shown.pattern) else {
            return;
        };
        let lens_name = match self.entry_mode(shown) {
            midi_typing::EntryMode::Degree { .. } => "degrees",
            midi_typing::EntryMode::Chromatic => "notes",
        };
        let lens_view = lens::LensView::resolve(lens_name, &self.song.key, &|_| None);
        let notes = sequencer::note_views(pattern, &self.song.key);
        let name = pattern.name.clone();
        let clip = sequence::ClipView {
            id: shown.pattern.0,
            name: &name,
            length_ticks: sequencer::pattern_length(&self.song, shown.pattern),
            notes: &notes,
            ghosts: &[],
        };
        let focused = self.inside.is_some() && self.browser.is_none();

        // The sequencer sits at the tray's left, inside the field's own
        // margin, and no wider than its natural width: a grid that
        // stretched with the window would be a grid the eye relearns.
        let margin = design::px(design::space::ROOM);
        let area = egui::Rect::from_min_max(
            egui::pos2(tray.min.x + margin, tray.min.y),
            egui::pos2(
                (tray.max.x - margin).min(tray.min.x + margin + CLIP_W_MAX),
                tray.max.y,
            ),
        );
        let mut child = ui.new_child(egui::UiBuilder::new().max_rect(area).id_salt("stage-clip"));
        // Computed BEFORE the panel borrows the sequencer: the moment is
        // a fact about the song and the transport, not about the editor.
        let playhead = self.playhead(shown);
        let outcome = self.sequencer.show(
            &mut child,
            focused,
            grammar::Voice {
                sentence: &mut self.sentence,
                registers: &mut self.registers,
            },
            self.entered_pitch.take(),
            Some(clip),
            &lens_view,
            self.polarity,
            playhead,
        );
        if focused {
            self.apply_sequence(shown.pattern, &outcome.intents);
            // The level under the cursor mirrors the sequencer's step, so
            // the ancestry strip tells the truth about where the performer is.
            if let Some(tick) = outcome.cursor_tick {
                let step = (tick / PATTERN_STEP_TICKS).min(PATTERN_STEPS - 1);
                if let FocusScope::Grid(grid) = self.focus.active_mut() {
                    grid.set_cursor(step % PATTERN_COLS, step / PATTERN_COLS);
                }
            }
        } else {
            // A veil, not a repaint: the tray keeps every mark it would
            // have, one step down in value. Exactly one thing on the
            // screen is focus-bright, and while the cursor is on the
            // session that thing is the cursor.
            ui.painter().rect_filled(area, 0.0, self.veil());
            // A click in the tray is the pointer's way in, the same
            // road Enter takes.
            if outcome.claim_focus && self.browser.is_none() {
                let _ = self.apply(StageIntent::Enter);
            }
        }
    }

    fn draw_field(&self, painter: &egui::Painter, avail: egui::Rect) {
        if let Some((lattice, cursor_shade)) = self.session_lattice() {
            self.draw_tracks(painter, avail, lattice, cursor_shade);
            self.draw_master(painter, avail, cursor_shade);
            // One lattice, two contents. The heads above are the same
            // heads either way — only what hangs beneath them changes.
            if self.mixing {
                self.draw_mixer(painter, avail, lattice, cursor_shade);
            } else {
                self.draw_scenes(painter, avail, lattice, cursor_shade);
            }
            return;
        }

        let FocusScope::Grid(active) = self.focus.active() else {
            return;
        };
        let cols = active.cols() as f32;
        let rows = active.rows() as f32;

        // The grid sits centred at a fixed aspect: cells are square, the
        // gap scales with the cell, and nothing about the layout ever
        // depends on where focus is — geometry is constant by rule.
        let cell = ((avail.width() / cols).min(avail.height() / rows) * 0.82).floor();
        let gap = (cell * 0.14).floor().max(2.0);
        let span_x = cols * cell + (cols - 1.0) * gap;
        let span_y = rows * cell + (rows - 1.0) * gap;
        let origin = egui::pos2(
            (avail.center().x - span_x / 2.0).floor(),
            (avail.center().y - span_y / 2.0).floor(),
        );

        // Exactly one thing on the screen is ever FOCUS-bright. While the
        // browser holds the cursor, the field keeps a RESTING mark instead
        // — where focus will land when it comes back, not where it is.
        let cursor_shade = if self.browser.is_some() {
            self.resting()
        } else {
            self.focused()
        };

        let (focus_col, focus_row) = active.cursor();
        for row in 0..active.rows() {
            for col in 0..active.cols() {
                let rect = egui::Rect::from_min_size(
                    origin + egui::vec2(col as f32 * (cell + gap), row as f32 * (cell + gap)),
                    egui::vec2(cell, cell),
                );
                let shade = if (col, row) == (focus_col, focus_row) {
                    cursor_shade
                } else {
                    self.square()
                };
                painter.rect_filled(rect, 0.0, shade);
            }
        }

        // The absorbed keystroke, present only on frames where a refusal
        // happened, in the field's own geometry.
        let field = egui::Rect::from_min_size(origin, egui::vec2(span_x, span_y));
        let focused = egui::Rect::from_min_size(
            origin
                + egui::vec2(
                    focus_col as f32 * (cell + gap),
                    focus_row as f32 * (cell + gap),
                ),
            egui::vec2(cell, cell),
        );
        self.draw_grid_refusal(painter, field, focused, gap.max(4.0));
    }

    /// The absorbed keystroke in a grid's geometry. Each limit refuses in
    /// its own shape: an edge marks its side, the root marks the whole
    /// field, the depth cap marks the square that would not open.
    fn draw_grid_refusal(
        &self,
        painter: &egui::Painter,
        field: egui::Rect,
        focused: egui::Rect,
        inset: f32,
    ) {
        match self.refusal.map(|refusal| refusal.reason) {
            Some(RefusalReason::Edge(step)) => {
                let (a, b) = match step {
                    Step::Up => (
                        egui::pos2(field.left(), field.top() - inset),
                        egui::pos2(field.right(), field.top() - inset),
                    ),
                    Step::Down => (
                        egui::pos2(field.left(), field.bottom() + inset),
                        egui::pos2(field.right(), field.bottom() + inset),
                    ),
                    Step::Left => (
                        egui::pos2(field.left() - inset, field.top()),
                        egui::pos2(field.left() - inset, field.bottom()),
                    ),
                    Step::Right => (
                        egui::pos2(field.right() + inset, field.top()),
                        egui::pos2(field.right() + inset, field.bottom()),
                    ),
                };
                painter.line_segment([a, b], egui::Stroke::new(2.0, self.refusal_ink()));
            }
            Some(RefusalReason::Shallower) => {
                painter.rect_stroke(
                    field.expand(inset),
                    0.0,
                    egui::Stroke::new(2.0, self.refusal_ink()),
                    egui::StrokeKind::Outside,
                );
            }
            Some(RefusalReason::Deeper) => {
                painter.rect_stroke(
                    focused.expand((inset * 0.5).max(2.0)),
                    0.0,
                    egui::Stroke::new(2.0, self.refusal_ink()),
                    egui::StrokeKind::Outside,
                );
            }
            // A refusal that happened in the browser has no geometry in
            // the field — it belongs to the other side of the screen, and
            // the message strip is where it is reported. An empty or
            // unavailable verb on a step is reported the same way.
            Some(RefusalReason::Empty | RefusalReason::AtTop | RefusalReason::Unavailable)
            | None => {}
        }
    }

    /// The track strip: every track in the song, across the top of the
    /// field, one column each. Identity only — name and kind — because a
    /// surface has to say what its objects ARE before it can say what they
    /// are doing.
    fn draw_tracks(
        &self,
        painter: &egui::Painter,
        field: egui::Rect,
        lattice: &FocusLattice,
        cursor_shade: egui::Color32,
    ) {
        let heads = tracks::heads(&self.song);
        if heads.is_empty() {
            return;
        }

        let gap = column_gap();
        let rows_gap = row_gap();
        let margin = design::px(design::space::ROOM);
        let pad = design::px(design::space::STEP);
        let name_font = egui::FontId::monospace(design::px(design::type_scale::BODY));
        let kind_font = egui::FontId::monospace(design::px(design::type_scale::MICRO));
        let top = field.min.y + margin;

        let window = self.strip_window(field);
        let (first, last) = (window.start, window.end);
        let shown = &heads[window];

        for (slot, head) in shown.iter().enumerate() {
            let index = first + slot;
            let rect = Self::head_rect(field, slot);
            let focused = lattice.cursor() == Some((index, 0));
            // No outline: the column is a lighter plane than the field
            // it sits on, and the gap between columns is the field showing
            // through. The edge was drawing a boundary the value already
            // drew.
            ornament::plane(
                painter,
                rect,
                if focused { cursor_shade } else { self.square() },
                // The strip is ONE band with two shoulders, not a row of
                // separately bevelled tiles: the first track gives up its
                // left corner, the last its right, and everything between
                // them is square. A cut in the middle of a run would be a
                // shoulder where the band does not end.
                //
                // The ends are the SONG's, not the window's, so scrolling
                // never moves a shoulder onto a track that is not one —
                // ornament that shifted as the view moved would be
                // varying with something it does not mean.
                match (index == 0, index + 1 == heads.len()) {
                    (true, _) => Some(ornament::Cut::TopLeft),
                    (_, true) => Some(ornament::Cut::TopRight),
                    _ => None,
                },
            );
            if focused {
                // The bracket is this app's cursor form — it was already
                // the step grid's, and it is the house's now.
                ornament::brackets(
                    painter,
                    rect.expand(3.0),
                    self.alphabet().ink.color,
                    1.0,
                    8.0,
                );
            }

            // The family this track sounds, as its own mark. A chain's
            // head decides it; a track with no chain sounds the default
            // voice and says so with the same sign the browser files it
            // under, so the shape means one thing in both places.
            // The mark takes the head's top-right corner, and the name
            // is cut to leave it. A name that ran under the sigil would
            // be two things in one place, which is the failure the whole
            // ornament rule exists to avoid.
            let sigil_side = design::px(design::space::STEP);
            let sigil_room = sigil_side + pad;
            if let Some(mark) = self.track_sigil(index) {
                glyph::paint(
                    painter,
                    egui::Rect::from_center_size(
                        egui::pos2(
                            rect.max.x - pad - sigil_side / 2.0,
                            rect.min.y + pad * 0.9 + sigil_side / 2.0,
                        ),
                        egui::Vec2::splat(sigil_side),
                    ),
                    mark,
                    if focused {
                        self.alphabet().well.color
                    } else {
                        self.alphabet().edge.color
                    },
                );
            }

            // The focused column inverts, exactly as the field's cursor
            // inverts: one signal drawn one way everywhere. Within the
            // column the name outranks the kind on both sides of the
            // inversion, so the reading order survives it.
            // Both lines carry the content rung: a head's kind and its
            // number are facts to be READ, and at the structure rung on a
            // near-black plane they were closer to the ground than to the
            // name beside them. The name still outranks the kind — by SIZE,
            // which was always doing that work as well.
            let (name_ink, kind_ink) = if focused {
                (self.alphabet().ground.color, self.alphabet().well.color)
            } else {
                (self.alphabet().ink.color, self.alphabet().ink.color)
            };
            // While this head is being renamed the letters typed so far
            // ARE its name, with a caret to say the word is not finished.
            let name = match &self.renaming {
                Some(rename) if rename.track == index => format!("{}_", rename.text),
                _ => head.name.clone(),
            };
            // Cut to leave the sigil its corner: a name that ran under
            // the mark would be two things in one place.
            let name = {
                let cell = painter
                    .layout_no_wrap("M".to_owned(), name_font.clone(), name_ink)
                    .rect
                    .width()
                    .max(1.0);
                let cells =
                    (((rect.width() - pad * 2.0 - sigil_room) / cell).floor()).max(1.0) as usize;
                name.chars().take(cells).collect::<String>()
            };
            painter.text(
                egui::pos2(rect.min.x + pad, rect.min.y + pad),
                egui::Align2::LEFT_TOP,
                name,
                name_font.clone(),
                name_ink,
            );
            painter.text(
                egui::pos2(rect.min.x + pad, rect.max.y - pad),
                egui::Align2::LEFT_BOTTOM,
                head.kind,
                kind_font.clone(),
                kind_ink,
            );
            // The column's address, the way the sequencer numbers its
            // rows: a track is a channel with a number before it has a
            // name, and the number is what a held key will one day say.
            // On the kind's line, not the name's: a name may run the
            // whole width, and the number must never be under it.
            painter.text(
                egui::pos2(rect.max.x - pad, rect.max.y - pad),
                egui::Align2::RIGHT_BOTTOM,
                format!("{:02}", index + 1),
                kind_font.clone(),
                kind_ink,
            );
        }

        // A line down each gap between columns.
        //
        // The gap alone divided them on a black ground, where a column is
        // a plane against nothing. On paper the same gap is a narrow band
        // of near-white between two other near-whites, and a boundary the
        // eye has to look for is a boundary that is not doing its job.
        //
        // BETWEEN the columns and not around each one: an outline per
        // column would draw every seam twice and put a line down the
        // outside edges, where there is nothing to separate.
        let margin_bottom = field.max.y - margin;
        for slot in 1..shown.len() {
            let x = (Self::head_rect(field, slot).min.x - gap / 2.0).floor() + 0.5;
            painter.line_segment(
                [egui::pos2(x, top), egui::pos2(x, margin_bottom)],
                egui::Stroke::new(1.0, self.alphabet().edge.color),
            );
        }

        // The absorbed keystroke, in the session's own geometry: the
        // heads and every drawn scene row together, because the cursor
        // can be refused at the bottom of the lattice as well as at the
        // top of the strip. Every edge is drawn, because a swallowed key
        // is indistinguishable from a broken one.
        let drawn = shown.len() as f32;
        let rows = self.scene_window(field).len() as f32;
        let span = egui::Rect::from_min_size(
            egui::pos2(field.min.x + margin, top),
            egui::vec2(
                ADDRESS_W + drawn * TRACK_W + (drawn - 1.0) * gap,
                TRACK_H + section_gap() + rows * (scenes::SLOT_H + rows_gap),
            ),
        );
        let inset = gap.max(4.0);

        // Tracks the window is not showing. A SHORT tick, where a refusal
        // is a full-height rule: the two can never appear on the same edge
        // at the same time — a step toward hidden tracks scrolls instead of
        // refusing — but they are still different marks, because a
        // performer must not have to reason about which one they are
        // looking at.
        let elsewhere = TRACK_H / 3.0;
        let middle = top + TRACK_H / 2.0;
        if first > 0 {
            painter.line_segment(
                [
                    egui::pos2(span.left() - inset, middle - elsewhere / 2.0),
                    egui::pos2(span.left() - inset, middle + elsewhere / 2.0),
                ],
                egui::Stroke::new(2.0, self.alphabet().ink.color),
            );
        }
        if last < heads.len() {
            painter.line_segment(
                [
                    egui::pos2(span.right() + inset, middle - elsewhere / 2.0),
                    egui::pos2(span.right() + inset, middle + elsewhere / 2.0),
                ],
                egui::Stroke::new(2.0, self.alphabet().ink.color),
            );
        }
        match self.refusal.map(|refusal| refusal.reason) {
            Some(RefusalReason::Edge(step)) => {
                let (a, b) = match step {
                    Step::Up => (
                        egui::pos2(span.left(), span.top() - inset),
                        egui::pos2(span.right(), span.top() - inset),
                    ),
                    Step::Down => (
                        egui::pos2(span.left(), span.bottom() + inset),
                        egui::pos2(span.right(), span.bottom() + inset),
                    ),
                    Step::Left => (
                        egui::pos2(span.left() - inset, span.top()),
                        egui::pos2(span.left() - inset, span.bottom()),
                    ),
                    Step::Right => (
                        egui::pos2(span.right() + inset, span.top()),
                        egui::pos2(span.right() + inset, span.bottom()),
                    ),
                };
                painter.line_segment([a, b], egui::Stroke::new(2.0, self.refusal_ink()));
            }
            Some(RefusalReason::Shallower) => {
                painter.rect_stroke(
                    span.expand(inset),
                    0.0,
                    egui::Stroke::new(2.0, self.refusal_ink()),
                    egui::StrokeKind::Outside,
                );
            }
            _ => {}
        }
    }

    /// The master: one column, pinned right, in both contents.
    ///
    /// It carries a head like a track's — so the eye reads it as a column
    /// of the same kind — and beneath it whatever the lattice is showing:
    /// its own channel strip in the mixer, and in the session nothing,
    /// because the master holds no clips and a column of empty slots
    /// would invite firing one.
    fn draw_master(&self, painter: &egui::Painter, field: egui::Rect, cursor_shade: egui::Color32) {
        let alpha = self.alphabet();
        let pad = design::px(design::space::STEP);
        let margin = design::px(design::space::ROOM);
        let gap = row_gap();
        let name_font = egui::FontId::monospace(design::px(design::type_scale::BODY));
        let kind_font = egui::FontId::monospace(design::px(design::type_scale::MICRO));
        let head = Self::master_rect(field);
        let focused = self.session_address() == Some(Address::Master);

        painter.rect_filled(
            head,
            0.0,
            if focused { cursor_shade } else { self.square() },
        );
        let (name_ink, kind_ink) = if focused {
            (alpha.ground.color, alpha.well.color)
        } else {
            (alpha.ink.color, alpha.ink.color)
        };
        painter.text(
            egui::pos2(head.min.x + pad, head.min.y + pad),
            egui::Align2::LEFT_TOP,
            "Master",
            name_font,
            name_ink,
        );
        painter.text(
            egui::pos2(head.min.x + pad, head.max.y - pad),
            egui::Align2::LEFT_BOTTOM,
            "Out",
            kind_font,
            kind_ink,
        );

        // A line down its left side, the same one the tracks have between
        // them — it is a column beside the others, not a thing apart.
        let seam = (head.min.x - column_gap() / 2.0).floor() + 0.5;
        painter.line_segment(
            [
                egui::pos2(seam, head.min.y),
                egui::pos2(seam, field.max.y - margin),
            ],
            egui::Stroke::new(1.0, alpha.edge.color),
        );

        if !self.mixing {
            return;
        }
        let strip = mixer::strip_beneath(head, field.max.y - margin, gap);
        mixer::draw(
            painter,
            strip,
            &mixer::Channel {
                gain: self.song.master,
                pan: 0.0,
                muted: false,
                soloed: false,
                // The master is always in the path: everything that
                // sounds arrives here, and there is nothing above it that
                // could silence it.
                audible: true,
                switches: false,
                level: self.meters.master().level,
                peak: self.meters.master().peak,
            },
            design::px(design::space::SNUG),
            alpha,
        );
    }

    /// The mixer: one channel strip per shown track, hanging beneath its
    /// own head.
    ///
    /// Focus is NOT marked here. The cursor addresses a channel as a
    /// whole while the mixer is up, so the head above the strip is the
    /// cell the cursor stands in, and `draw_tracks` has already inverted
    /// it. Marking the strip too would spend focus ink twice on one
    /// thing — and dimming the other strips, the other way to show which
    /// is current, would destroy the comparison between levels that is
    /// the entire reason a mixer puts them side by side.
    fn draw_mixer(
        &self,
        painter: &egui::Painter,
        field: egui::Rect,
        _lattice: &FocusLattice,
        _cursor_shade: egui::Color32,
    ) {
        // The strip hangs under its head by the row gap, and keeps the
        // snug rhythm INSIDE itself: the lattice's spacing groups columns,
        // while a channel's own parts are spaced by what they are.
        let gap = row_gap();
        let inner = design::px(design::space::SNUG);
        let margin = design::px(design::space::ROOM);
        let tracks = self.strip_window(field);
        if tracks.is_empty() {
            return;
        }
        let bottom = field.max.y - margin;
        let channels = mixer::channels(&self.song, &self.meters.readings());
        for (slot, track) in tracks.enumerate() {
            let Some(channel) = channels.get(track) else {
                continue;
            };
            let head = Self::head_rect(field, slot);
            let strip = mixer::strip_beneath(head, bottom, gap);
            mixer::draw(painter, strip, channel, inner, self.alphabet());
        }
    }

    /// The scene lattice: one slot per (shown track, scene), stacked under
    /// the heads. Faint by construction — a resting slot is a SURFACE
    /// plane on the GROUND, the same step in value a head is, and the
    /// dimmest mark the alphabet has. It holds nothing yet, so it says
    /// nothing louder than "a place exists here".
    fn draw_scenes(
        &self,
        painter: &egui::Painter,
        field: egui::Rect,
        lattice: &FocusLattice,
        cursor_shade: egui::Color32,
    ) {
        let gap = row_gap();
        let pad = design::px(design::space::STEP);
        let font = egui::FontId::monospace(design::px(design::type_scale::MICRO));
        let tracks = self.strip_window(field);
        let rows = self.scene_window(field);
        if tracks.is_empty() || rows.is_empty() {
            return;
        }

        // The focused slot inverts, exactly as a head does: one signal,
        // drawn one way, wherever the cursor stands on the session.
        let focused = lattice
            .cursor()
            .map(|cursor| Address::of(cursor, self.song.tracks.len()));
        let focused_scene = match focused {
            Some(Address::Slot { scene, .. }) => Some(scene),
            _ => None,
        };

        // The scene addresses, in the gutter: the row's number, lit when
        // the cursor is on that row and quiet otherwise. The heads get no
        // number here because their number is on them.
        let gutter_x = Self::head_rect(field, 0).min.x - column_gap();
        for (line, scene) in rows.clone().enumerate() {
            let rect = scenes::slot_beneath(Self::head_rect(field, 0), line, gap, section_gap());
            let ink = if focused_scene == Some(scene) {
                self.alphabet().ink.color
            } else {
                self.alphabet().edge.color
            };
            painter.text(
                egui::pos2(gutter_x, rect.center().y),
                egui::Align2::RIGHT_CENTER,
                format!("{:02}", scene + 1),
                font.clone(),
                ink,
            );
        }

        for (slot, track) in tracks.clone().enumerate() {
            let head = Self::head_rect(field, slot);
            for (line, scene) in rows.clone().enumerate() {
                let rect = scenes::slot_beneath(head, line, gap, section_gap());
                let here = focused == Some(Address::Slot { track, scene });
                let mark = scenes::mark(&self.song, track, scene);

                // Every cell is bounded, faintly, whether or not anything
                // is in it.
                //
                // The rank and file used to be carried by the points
                // alone, which asks the eye to infer a grid from a
                // scattering of marks — and on a paper ground, where the
                // resting rungs sit inside a narrow band, that inference
                // is work. A hairline at low opacity states the lattice
                // instead of implying it, and stays quiet enough that the
                // clips remain the figure and this remains the ground.
                //
                // Opacity rather than a rung: the alphabet's ladder is a
                // set of VALUES for things that speak, and this does not
                // speak. It is the same edge every region is bounded with,
                // held back to a third of itself.
                painter.rect_stroke(
                    rect,
                    0.0,
                    egui::Stroke::new(1.0, self.alphabet().edge.color.gamma_multiply(0.35)),
                    egui::StrokeKind::Inside,
                );

                // Three states, three values. The cursor is a plane in the
                // focus shade. A clip is a plane one rung up from the
                // ground. An empty place is a point — the lattice shows
                // through as rank and file, and nothing else.
                if here {
                    ornament::plane(
                        painter,
                        rect,
                        cursor_shade,
                        Some(ornament::Cut::BottomRight),
                    );
                    ornament::brackets(
                        painter,
                        rect.expand(3.0),
                        self.alphabet().ink.color,
                        1.0,
                        6.0,
                    );
                } else if mark.is_some() {
                    // A clip is the FIGURE of this surface, and it was
                    // drawn on the same rung as the head above it — two
                    // different kinds of thing sharing one value, which is
                    // the one thing the code may not do. It goes up to the
                    // structure rung: clear of the ground, clear of the
                    // heads, and the brightest resting plane in the
                    // lattice, which is what a clip is.
                    ornament::plane(
                        painter,
                        rect,
                        self.alphabet().edge.color,
                        Some(ornament::Cut::BottomRight),
                    );
                } else {
                    // The empty place is still a point and not a plane —
                    // but at the structure rung it was a mark the eye had
                    // to hunt for, and rank and file cannot be read from
                    // marks that are not seen. It carries the content rung
                    // now: the lattice is quiet, not invisible.
                    painter.rect_filled(
                        egui::Rect::from_center_size(rect.center(), egui::Vec2::splat(POINT)),
                        0.0,
                        self.alphabet().ink.color,
                    );
                }

                // What is SOUNDING, in the alphabet's word for it. LIVE is
                // documented as "the playhead, what is making sound right
                // now" — and its dim partner as the same meaning present
                // but not the subject, which is exactly a clip that is
                // launched while the transport is parked.
                //
                // A bar at the slot's leading edge rather than a tint of
                // the whole plane: the plane is already carrying focus and
                // occupancy, and a third meaning laid over both would make
                // all three harder to read.
                if self.playing_on(track) == Some(scene) {
                    // The bar BREATHES on the beat while it rolls: bright
                    // on the downbeat, decaying across it, back at the
                    // next. Motion that is state rather than decoration —
                    // it is the tempo, made visible on the thing the
                    // tempo is moving, and it means a glance at the
                    // session tells you the song is running without
                    // reading a number.
                    let ink = if self.transport.motion().is_rolling() {
                        let phase = (self.transport.tick() % crate::sequencing::TICKS_PER_BEAT)
                            as f32
                            / crate::sequencing::TICKS_PER_BEAT as f32;
                        let (hot, cool) =
                            (self.alphabet().live.color, self.alphabet().live_dim.color);
                        // Eased so the decay reads as a falling thing
                        // rather than a linear ramp.
                        cool.lerp_to_gamma(hot, (1.0 - phase) * (1.0 - phase))
                    } else {
                        self.alphabet().live_dim.color
                    };
                    painter.rect_filled(
                        egui::Rect::from_min_size(rect.min, egui::vec2(POINT, rect.height())),
                        0.0,
                        ink,
                    );
                }

                // A filled slot: its kind at the left, its number at the
                // right, one quiet line between them. The sign is a rung
                // below the number — the number is the address, the sign
                // only says what kind of thing lives there. Both invert
                // with the fill so the mark survives being focused.
                let Some(mark) = mark else {
                    continue;
                };
                // The sign stays a rung below the number on both sides of
                // the inversion. On a lit clip that rung is the GROUND
                // showing through its own plane — engraved rather than
                // printed — because above the structure rung there is
                // nothing quieter left to say it with.
                let (sign_ink, number_ink) = if here {
                    (self.alphabet().surface.color, self.alphabet().ground.color)
                } else {
                    (self.alphabet().ground.color, self.alphabet().ink.color)
                };
                painter.text(
                    egui::pos2(rect.min.x + pad, rect.center().y),
                    egui::Align2::LEFT_CENTER,
                    mark.glyph.to_string(),
                    font.clone(),
                    sign_ink,
                );
                painter.text(
                    egui::pos2(rect.max.x - pad, rect.center().y),
                    egui::Align2::RIGHT_CENTER,
                    &mark.number,
                    font.clone(),
                    number_ink,
                );
            }
        }

        // Scenes the window is not showing, marked the way hidden tracks
        // are: a short tick past the edge they lie beyond.
        let first_slot = scenes::slot_beneath(Self::head_rect(field, 0), 0, gap, section_gap());
        let last_slot = scenes::slot_beneath(
            Self::head_rect(field, 0),
            rows.len() - 1,
            gap,
            section_gap(),
        );
        let elsewhere = TRACK_W / 3.0;
        let middle = first_slot.center().x;
        let inset = gap.max(4.0);
        if rows.start > 0 {
            painter.line_segment(
                [
                    egui::pos2(middle - elsewhere / 2.0, first_slot.top() - inset),
                    egui::pos2(middle + elsewhere / 2.0, first_slot.top() - inset),
                ],
                egui::Stroke::new(2.0, self.alphabet().ink.color),
            );
        }
        if rows.end < self.song.session.scenes.len() {
            painter.line_segment(
                [
                    egui::pos2(middle - elsewhere / 2.0, last_slot.bottom() + inset),
                    egui::pos2(middle + elsewhere / 2.0, last_slot.bottom() + inset),
                ],
                egui::Stroke::new(2.0, self.alphabet().ink.color),
            );
        }
    }

    /// The ancestry zone: one miniature grid per level above the active
    /// one, root first, each with its entered square lit. It lives at the
    /// left end of the vitals strip — a constant home the eye learns once;
    /// at the root the strip is simply empty, which itself reads as "top
    /// level, all quiet".
    fn draw_breadcrumb(&self, painter: &egui::Painter, zone: egui::Rect) {
        const MINI_CELL: f32 = 5.0;
        const MINI_GAP: f32 = 1.0;
        const MARGIN: f32 = 16.0;
        const SPACING: f32 = 12.0;

        let levels = self.focus.levels();
        let ancestors = &levels[..levels.len() - 1];
        // Every shape draws through its miniature, so an ancestor the eye
        // must account for is never silently skipped — a level that drew
        // nothing would report "top level, all quiet" from inside a
        // descent, which is a false ancestry rather than a missing mark.
        let tallest = ancestors
            .iter()
            .map(|scope| scope.miniature().rows)
            .max()
            .unwrap_or(0);
        if tallest == 0 {
            return;
        }

        let mini_h = tallest as f32 * (MINI_CELL + MINI_GAP) - MINI_GAP;
        let top = (zone.center().y - mini_h / 2.0).floor();
        let mut corner = egui::pos2(zone.min.x + MARGIN, top);
        for scope in ancestors {
            let level = scope.miniature();
            if level.cols == 0 || level.rows == 0 {
                continue;
            }
            let span = egui::vec2(
                level.cols as f32 * (MINI_CELL + MINI_GAP) - MINI_GAP,
                level.rows as f32 * (MINI_CELL + MINI_GAP) - MINI_GAP,
            );
            // Shorter shapes sit centred against the tallest, so the strip
            // reads as one row of levels rather than a ragged top edge.
            corner.y = (top + (mini_h - span.y) / 2.0).floor();
            for row in 0..level.rows {
                for col in 0..level.cols {
                    let rect = egui::Rect::from_min_size(
                        corner
                            + egui::vec2(
                                col as f32 * (MINI_CELL + MINI_GAP),
                                row as f32 * (MINI_CELL + MINI_GAP),
                            ),
                        egui::vec2(MINI_CELL, MINI_CELL),
                    );
                    let shade = if (col, row) == (level.col, level.row) {
                        self.focused()
                    } else {
                        self.square()
                    };
                    painter.rect_filled(rect, 0.0, shade);
                }
            }
            corner.x += span.x + SPACING;
        }
    }

    /// The time end of the vitals strip. It reports but never acts: the
    /// keyboard moves time, and focus remains in the sovereign field.
    /// The engine's own state, on the periphery, as one mark.
    ///
    /// Only drawn when there is NO engine. A running one is the ordinary
    /// case and needs no announcement — a light that is always on says
    /// nothing — while silence with nothing behind the stage is a
    /// different problem from silence with a full graph, and a surface
    /// that draws them identically makes the reader guess which they have.
    ///
    /// It is JEOPARDY rather than ink: nothing this frame does will make
    /// a sound, and that is a thing at stake rather than a fact to read.
    fn draw_engine(&self, painter: &egui::Painter, zone: egui::Rect) {
        let margin = design::px(design::space::ROOM);
        let gap = design::px(design::space::ROOM);
        let font = egui::FontId::monospace(design::px(design::type_scale::MICRO));
        let alpha = self.alphabet();
        let mut right = zone.max.x - margin;

        // The song's name, and whether it is safe. Structure ink: a fact
        // to read when looked for, never a thing that competes with the
        // message beside it.
        let title = self
            .path
            .as_deref()
            .map(document::title)
            .unwrap_or_else(|| "untitled".to_owned());
        let title = if self.dirty {
            format!("{title} *")
        } else {
            title
        };
        let title_rect = painter.text(
            egui::pos2(right, zone.center().y),
            egui::Align2::RIGHT_CENTER,
            title,
            font.clone(),
            alpha.edge.color,
        );
        right = title_rect.min.x - gap;

        // The engine, in as many words as it needs and no more: a
        // running engine says nothing, a dropped block says so loudly
        // for as long as it takes to be seen, and the count stays behind
        // quietly for whoever looks later.
        let Some((words, tone)) = self.vitals.words() else {
            return;
        };
        let ink = match tone {
            vitals::Tone::Alarm => alpha.jeopardy_active.color,
            vitals::Tone::Quiet => alpha.edge.color,
        };
        painter.text(
            egui::pos2(right, zone.center().y),
            egui::Align2::RIGHT_CENTER,
            words,
            font,
            ink,
        );
    }

    fn draw_transport(&self, painter: &egui::Painter, zone: egui::Rect) {
        let place = self.transport.place(&self.song);
        let readout = place.readout();
        let beats = beat_cells(place);
        let tempo = format!(
            "{:.0}",
            self.song
                .bpm_at(self.transport.tick(), transport::DEFAULT_BPM)
        );

        let body = egui::FontId::monospace(design::px(design::type_scale::BODY));
        let quiet = egui::FontId::monospace(design::px(design::type_scale::MICRO));
        let margin = design::px(design::space::ROOM);
        let gap = design::px(design::space::ROOM);
        let center_y = zone.center().y;
        let mut right = zone.max.x - margin;

        let tempo_rect = painter.text(
            egui::pos2(right, center_y),
            egui::Align2::RIGHT_CENTER,
            tempo,
            quiet,
            self.alphabet().ink.color,
        );
        right = tempo_rect.min.x - gap;

        let beat_color = if self.transport.motion().is_rolling() {
            self.alphabet().live.color
        } else {
            self.alphabet().ink.color
        };
        let beat_rect = painter.text(
            egui::pos2(right, center_y),
            egui::Align2::RIGHT_CENTER,
            beats,
            body.clone(),
            beat_color,
        );
        right = beat_rect.min.x - gap;

        let readout_rect = painter.text(
            egui::pos2(right, center_y),
            egui::Align2::RIGHT_CENTER,
            readout,
            body.clone(),
            self.alphabet().ink.color,
        );

        if self.transport.motion() == Motion::Recording {
            painter.text(
                egui::pos2(readout_rect.min.x - gap, center_y),
                egui::Align2::RIGHT_CENTER,
                "REC",
                body,
                self.alphabet().jeopardy_active.color,
            );
        }
    }

    /// The message zone: the frame's refusal named in words, in the same
    /// gray as the geometric marks and gone the same frame they are. Empty
    /// is the normal state — this strip earns ink only when something was
    /// declined (and later: confirmed, landed, or failed).
    /// The browser: a window that opens ABOVE the work rather than
    /// alongside it.
    ///
    /// Its own opaque ground, so what is beneath is hidden rather than
    /// shining through, and one edge to say where it ends. Nothing under
    /// it moves — it covers the corner it covers and then gives it back.
    ///
    fn draw_browser(&self, painter: &egui::Painter, zone: egui::Rect) {
        let Some(browser) = &self.browser else {
            return;
        };
        // The browser is a PLANE above the work, and its lightness is what
        // says so. It needs no edge drawn along it: a raised surface is
        // already legible as one, and an outline would be the drawing
        // apologising for the value not being trusted.
        // A well, not a surface: the browser is a window cut into the
        // ground, and sits below the planes it covers rather than among them.
        painter.rect_filled(zone, 0.0, self.alphabet().well.color);

        let line = design::px(design::type_scale::BODY);
        let font = egui::FontId::monospace(line);
        let inset = design::px(design::space::ROOM);
        let measure =
            painter.layout_no_wrap("M".to_owned(), font.clone(), self.alphabet().ink.color);
        let cell = measure.size();
        let columns = ((zone.width() - inset * 2.0) / cell.x).floor() as usize;
        let rows = ((zone.height() - inset * 2.0) / cell.y).floor() as usize;
        if columns < 8 || rows < 5 {
            return;
        }

        let inner = columns - 2;
        let origin = egui::pos2(zone.min.x + inset, zone.min.y + inset);
        let at = |column: usize, row: usize| {
            origin + egui::vec2(column as f32 * cell.x, row as f32 * cell.y)
        };
        let text = |position: egui::Pos2, words: String, color: egui::Color32| {
            painter.text(position, egui::Align2::LEFT_TOP, words, font.clone(), color);
        };

        let bottom = rows - 1;

        // The pane's rules are DRAWN, not typed. Ruling characters are one
        // glyph per cell, so a border made of them is a row of separate
        // marks with a seam at every cell boundary and a baseline that is
        // not the cell's centre — at this size that reads as hatching
        // rather than as a line. `ui::glyph` already made this argument
        // for the family marks; the same reasoning ends at the same place.
        // A segment is one stroke, pixel-aligned, the same on every
        // machine, and independent of what the font happens to carry.
        let half = egui::vec2(cell.x / 2.0, cell.y / 2.0);
        let snap = |point: egui::Pos2| egui::pos2(point.x.round(), point.y.round());
        let frame =
            egui::Rect::from_min_max(snap(at(0, 0) + half), snap(at(columns - 1, bottom) + half));
        // What is being typed sits in a WELL: a step down from the plane
        // it is cut into, which divides it from the list without a rule
        // between them. A recess also says what the band is for — you
        // write into a surface, not onto one.
        let divider = snap(at(0, 2) + half).y;
        painter.rect_filled(
            egui::Rect::from_min_max(
                egui::pos2(frame.left(), frame.top()),
                egui::pos2(frame.right(), divider),
            ),
            0.0,
            self.alphabet().ground.color,
        );

        // The surface's ONE mute flourish, and the only mark in this pane
        // carrying neither command nor state — the precedent is the
        // transport's phase marks. It is the luminance ladder the pane is
        // drawn from, signed into the bottom rule: three rungs ascending.
        //
        // Two are missing, and their absence is the whole of it. GROUND is
        // the page it would be drawn on, and FOCUS is spent on the cursor,
        // which a signature is not allowed to borrow. A flourish that
        // shouted would be claiming importance it does not have.
        //
        // Recorded as a flourish because the charter permits exactly one
        // per surface and forbids a second: if another is ever wanted
        // here, this is the one that has to go.
        let alpha = self.alphabet();
        let rungs = [alpha.surface, alpha.edge, alpha.ink];
        let pitch = design::px(design::space::SNUG);
        let rise = design::px(design::space::HAIR);
        let mut signature = egui::pos2(frame.right() - pitch * rungs.len() as f32, frame.bottom());
        for rung in rungs {
            painter.line_segment(
                [signature, egui::pos2(signature.x, signature.y - rise)],
                egui::Stroke::new(1.0, rung.color),
            );
            signature.x += pitch;
        }

        // The yield of what has been typed, in the row where it is being
        // typed. A keystroke earns its place by removing uncertainty, and
        // this is the only place the reader can see whether the last one
        // did — the moment the number stops falling, arrowing is cheaper
        // than typing.
        let yield_mark = if browser.query().is_empty() {
            String::new()
        } else {
            browser.surviving_leaves().to_string()
        };
        let typed = fit_cells(
            &format!("{} {}", browser::glyph::PROMPT, browser.query()),
            inner.saturating_sub(yield_mark.chars().count() + 1),
        );
        text(at(1, 1), typed, self.alphabet().ink.color);
        if !yield_mark.is_empty() {
            let column = columns - 1 - yield_mark.chars().count();
            text(at(column, 1), yield_mark, self.alphabet().edge.color);
        }

        // One drawable line per visible row, plus a NOTE under any open
        // shelf that has nothing to show. The note sits where the missing
        // rows would be, because a sign beside the thing it describes is
        // stronger than a status message detached from it.
        enum Line<'a> {
            Row(usize, &'a browser::Row, &'a Node),
            Note(usize, String),
        }

        let tree = browser.rows();
        let mut lines = Vec::new();
        for (index, row) in tree.iter().enumerate() {
            let Some(node) = browser.node_at(&row.path) else {
                continue;
            };
            lines.push(Line::Row(index, row, node));
            let EntryKind::Shelf(shelf) = node.kind else {
                continue;
            };
            if !node.expanded || !node.children.is_empty() {
                continue;
            }
            lines.push(Line::Note(
                row.depth + 1,
                match browser.status_of(shelf) {
                    BrowserStatus::Scanning => "Scanning".to_owned(),
                    BrowserStatus::Unavailable => "No source".to_owned(),
                    BrowserStatus::Ready => "Empty".to_owned(),
                },
            ));
        }
        if tree.is_empty() {
            lines.push(Line::Note(
                0,
                if browser.query().is_empty() {
                    "Empty".to_owned()
                } else {
                    "No match".to_owned()
                },
            ));
        }

        let visible = rows - 4;
        // Scroll by the LINE the cursor is on, so a note never pushes the
        // addressed row off the bottom.
        let addressed = browser.cursor().and_then(|cursor| {
            lines
                .iter()
                .position(|line| matches!(line, Line::Row(index, _, _) if *index == cursor))
        });
        let start = addressed
            .unwrap_or(0)
            .saturating_sub(visible / 2)
            .min(lines.len().saturating_sub(visible));

        for slot in 0..visible {
            let screen_row = 3 + slot;
            let Some(line) = lines.get(start + slot) else {
                continue;
            };
            match line {
                Line::Row(index, row, node) => {
                    let addressed = Some(*index) == browser.cursor();
                    if addressed {
                        painter.rect_filled(
                            egui::Rect::from_min_size(
                                at(1, screen_row),
                                egui::vec2(inner as f32 * cell.x, cell.y),
                            ),
                            0.0,
                            self.focused(),
                        );
                    }

                    // Depth is drawn, not implied: two cells per level, so
                    // the eye finds a heading's children by their left
                    // edge before reading a word of them.
                    let indent = row.depth * 2;

                    // The gate: two hairline segments, and whether it is
                    // open is said by WHERE the second one sits — across
                    // the middle while closed, dropped to the foot once
                    // open. The shape is the second frame's, which solved
                    // this before: an arrow glyph is a whole character of
                    // ink for one bit, and a column of them reads as a
                    // second margin competing with the labels.
                    //
                    // Copied rather than shared. `ui::kit` is the natural
                    // home for it, but every helper there takes a `Theme`
                    // and this frame carries none — and the frame it came
                    // from is the one being replaced. If the two ever have
                    // to agree, the SHAPE is the thing to lift.
                    let structure = if addressed {
                        self.alphabet().surface.color
                    } else {
                        self.alphabet().edge.color
                    };
                    let content = if addressed {
                        self.alphabet().ground.color
                    } else {
                        self.alphabet().ink.color
                    };
                    if node.is_branch() {
                        let arm = design::px(design::space::HAIR);
                        let hinge =
                            at(1 + indent, screen_row) + egui::vec2(cell.x / 2.0, cell.y / 2.0);
                        let ink = egui::Stroke::new(1.0, structure);
                        let back = (arm * 0.75).round();
                        painter.line_segment(
                            [
                                hinge + egui::vec2(-back, -arm),
                                hinge + egui::vec2(-back, arm),
                            ],
                            ink,
                        );
                        let foot = if node.expanded { arm } else { 0.0 };
                        painter.line_segment(
                            [
                                hinge + egui::vec2(-back, foot),
                                hinge + egui::vec2(arm, foot),
                            ],
                            ink,
                        );
                    }

                    // A CLOSED branch says how much is behind it. Opening a
                    // heading to find one device is a keystroke that bought
                    // nothing, and the count is the only way to know before
                    // spending it. Open branches drop it: the rows beneath
                    // are the answer, and a mark that repeats what is
                    // already on screen is ornament.
                    // Zero is a count, not a gap. Suppressing it would
                    // make ABSENCE carry the meaning "empty", which reads
                    // identically to a mark that failed to draw — and an
                    // empty shelf is worth exactly the keystroke it saves
                    // by saying so.
                    let count = if node.is_branch() && !node.expanded {
                        node.leaves().to_string()
                    } else {
                        String::new()
                    };
                    if !count.is_empty() {
                        let column = columns - 1 - count.chars().count();
                        text(at(column, screen_row), count.clone(), structure);
                    }

                    // The family's mark, in a cell reserved on EVERY row
                    // whether or not that row has one. A column that
                    // appeared and vanished would move the labels beside
                    // it, and geometry that shifts with content is
                    // geometry the eye has to re-learn each frame.
                    //
                    // Drawn at the structure rung: an esoteric mark
                    // whispers. One that shouted would be claiming an
                    // importance the heading does not have.
                    if let Some(mark) = node.mark {
                        let box_ = egui::Rect::from_min_size(
                            at(1 + indent + 1, screen_row),
                            egui::vec2(cell.x, cell.y),
                        );
                        glyph::paint(painter, box_.shrink(1.0), mark, structure);
                    }

                    // The label, character by character, so the ones the
                    // filter actually consumed can be told from the ones
                    // it merely passed over. With nothing typed every
                    // character is unmatched and the row is drawn flat, so
                    // this costs nothing until it says something.
                    let start = 1 + indent + 3;
                    let room =
                        (columns - 1)
                            .saturating_sub(start)
                            .saturating_sub(if count.is_empty() {
                                0
                            } else {
                                count.chars().count() + 1
                            });
                    let marks = browser::match_positions(&node.label, browser.query());
                    for (offset, letter) in node.label.chars().take(room).enumerate() {
                        let lit = marks.get(offset).copied().unwrap_or(false);
                        let ink = if lit && !addressed {
                            self.alphabet().focus.color
                        } else if lit {
                            self.alphabet().ground.color
                        } else if addressed {
                            self.alphabet().surface.color
                        } else {
                            content
                        };
                        text(at(start + offset, screen_row), letter.to_string(), ink);
                    }
                }
                // A note is never addressable, so it never inverts, and it
                // speaks a rung quieter than the rows it stands among.
                Line::Note(depth, words) => {
                    let indent = "  ".repeat(*depth);
                    text(
                        at(1, screen_row),
                        fit_cells(&format!("{indent}  {words}"), inner),
                        self.alphabet().edge.color,
                    );
                }
            }
        }

        // With no addressable row, the typing prompt becomes the one focus
        // signal. When a row exists its inversion is the signal instead.
        if browser.cursor().is_none() {
            painter.rect_filled(
                egui::Rect::from_min_size(at(1, 1), egui::vec2(cell.x, cell.y)),
                0.0,
                self.focused(),
            );
            text(
                at(1, 1),
                browser::glyph::PROMPT.to_string(),
                self.alphabet().ground.color,
            );
        }
    }

    /// The codebook for the scope focus is standing in, drawn from the
    /// keymap table itself.
    ///
    /// Two columns, both left-aligned on their own axis so the eye reads
    /// down either one: keys at [`design::FOCUS`] because they are the
    /// actionable half, meanings at [`design::INK`]. Monospace does the
    /// alignment for free, which is most of why the whole stage is
    /// monospace.
    fn draw_help(&self, painter: &egui::Painter, field: egui::Rect) {
        let scope = self.scope_context();
        let mut rows: Vec<(String, &'static str)> = keymap::bindings_for(scope)
            .map(|(modifiers, key, intent)| (keymap::chord_name(modifiers, key), intent.label()))
            .collect();
        if scope == keymap::ScopeContext::Clip {
            rows.extend(
                CLIP_HELP_EXAMPLES
                    .into_iter()
                    .map(|(chord, label)| (chord.to_owned(), label)),
            );
        }
        if rows.is_empty() {
            return;
        }

        let line = design::px(design::type_scale::BODY);
        let pitch = line + design::px(design::space::STEP);
        let key_w = design::px(design::space::VAST) * 2.0;
        let block_h = pitch * rows.len() as f32;

        let origin = egui::pos2(
            (field.center().x - key_w).floor(),
            (field.center().y - block_h / 2.0).floor(),
        );

        for (index, (chord, label)) in rows.iter().enumerate() {
            let y = origin.y + index as f32 * pitch + pitch / 2.0;
            painter.text(
                egui::pos2(origin.x + key_w, y),
                egui::Align2::RIGHT_CENTER,
                chord,
                egui::FontId::monospace(line),
                self.alphabet().focus.color,
            );
            painter.text(
                egui::pos2(origin.x + key_w + design::px(design::space::OPEN), y),
                egui::Align2::LEFT_CENTER,
                label,
                egui::FontId::monospace(line),
                self.alphabet().ink.color,
            );
        }
    }

    fn draw_message(&self, painter: &egui::Painter, zone: egui::Rect) {
        // The badge takes the strip's left shoulder, so everything the
        // strip has to SAY begins after it.
        const MARGIN: f32 = 44.0;

        let Some(refusal) = self.refusal else {
            // With no refusal this frame, the strip carries the
            // sequencer's last notice and the pitch-entry mode: a mode
            // must announce itself, and a refused edit must be read.
            let mut words = Vec::new();
            if self.midi_typing.enabled() {
                words.push("MIDI · letters are pitches");
            }
            // A mode that does not announce itself is a trap, and a
            // rename is a mode: every letter is the name until Enter.
            let renaming = self
                .renaming
                .as_ref()
                .map(|rename| format!("RENAME · {}_", rename.text));
            if let Some(renaming) = &renaming {
                words.push(renaming.as_str());
            } else if let Some(notice) = &self.notice {
                words.push(notice.as_str());
            }
            if !words.is_empty() {
                painter.text(
                    egui::pos2(zone.min.x + MARGIN, zone.center().y),
                    egui::Align2::LEFT_CENTER,
                    words.join("   "),
                    egui::FontId::monospace(16.0),
                    self.alphabet().ink.color,
                );
            }
            return;
        };
        let words = match refusal.reason {
            RefusalReason::Edge(Step::Up) => "Refused · edge up",
            RefusalReason::Edge(Step::Down) => "Refused · edge down",
            RefusalReason::Edge(Step::Left) => "Refused · edge left",
            RefusalReason::Edge(Step::Right) => "Refused · edge right",
            RefusalReason::Deeper => "Refused · depth limit",
            RefusalReason::Shallower => "Refused · no further out",
            RefusalReason::Empty => "Refused · nothing here yet",
            RefusalReason::AtTop => "Refused · already at top",
            RefusalReason::Unavailable => "Refused · no action yet",
        };
        painter.text(
            egui::pos2(zone.min.x + MARGIN, zone.center().y),
            egui::Align2::LEFT_CENTER,
            words,
            egui::FontId::monospace(16.0),
            self.refusal_ink(),
        );
    }
}

/// Fit one terminal row by CHARACTER count, never byte count. The stage's
/// vocabulary is monospace, so padding here is geometry rather than styling.
fn fit_cells(words: &str, width: usize) -> String {
    let mut fitted: String = words.chars().take(width).collect();
    fitted.extend(std::iter::repeat_n(
        ' ',
        width.saturating_sub(fitted.chars().count()),
    ));
    fitted
}

/// One terminal cell per score beat, with exactly the current one filled.
/// The row's length is the meter display; no spelled-out signature shadows
/// the song's authority.
fn beat_cells(place: Place) -> String {
    (1..=place.beats_per_bar)
        .map(|beat| {
            if beat == place.beat {
                browser::glyph::BLOCK
            } else {
                browser::glyph::SHADE_LIGHT
            }
        })
        .collect()
}

