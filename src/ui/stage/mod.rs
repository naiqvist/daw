    /// With the browser already up: find the named leaf and press it.
    fn enter_leaf(stage: &mut Stage, name: &str) -> ApplyOutcome {
        // Open shelves and headings until the named leaf is under the
        // cursor. The browser is a tree; this is a search, not a route.
        for _ in 0..400 {
            let here = stage
                .browser
                .as_ref()
                .and_then(Browser::selected)
                .map(|node| (node.label.clone(), node.is_branch()));
            match here {
                Some((label, false)) if label == name => {
                    return stage
                        .handle_key(Modifiers::NONE, Key::Enter)
                        .expect("enter is bound in the browser");
                }
                Some((_, true)) => {
                    let _ = stage.handle_key(Modifiers::NONE, Key::Enter);
                    let _ = stage.handle_key(Modifiers::NONE, Key::ArrowDown);
                }
                _ => {
                    let _ = stage.handle_key(Modifiers::NONE, Key::ArrowDown);
                }
            }
        }
        panic!("never found {name} in the browser");
    }

